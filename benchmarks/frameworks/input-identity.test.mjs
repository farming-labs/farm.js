import assert from "node:assert/strict";
import { promises as fs } from "node:fs";
import os from "node:os";
import path from "node:path";
import { test } from "node:test";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import {
  generatedBenchmarkOutputs,
  generatedOutputExclusions,
  inspectGeneratedOutputs,
} from "./input-policy.mjs";

// Exercise the runner's actual fingerprint code without launching frameworks.
const source = await fs.readFile(new URL("./run.mjs", import.meta.url), "utf8");
const start = source.indexOf("async function collectBenchmarkInputFiles(");
const end = source.indexOf("function readCommand(", start);
assert.ok(start > 0 && end > start);

async function setup(t) {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), "farm-input-identity-"));
  t.after(() => fs.rm(directory, { recursive: true, force: true }));
  const write = async (relative, content) => {
    const absolute = path.join(directory, relative);
    await fs.mkdir(path.dirname(absolute), { recursive: true });
    await fs.writeFile(absolute, content);
  };
  const runtime = new Function(
    "fs",
    "path",
    "createHash",
    "benchmarkDir",
    "generatedBenchmarkOutputs",
    `${source.slice(start, end)}; return { hashBenchmarkInputs, collectBenchmarkInputFiles };`,
  )(fs, path, createHash, directory, generatedBenchmarkOutputs);
  await write("apps/farm/src/app/page.tsx", "export default function Page() {}");
  return { directory, write, ...runtime };
}

for (const [file, content] of [
  ["apps/farm/src/farm.d.ts", "/** Generated by Farm.js. Do not edit. */"],
  [
    "apps/tanstack/src/routeTree.gen.ts",
    "// This file was automatically generated by TanStack Router.",
  ],
  ["apps/next/next-env.d.ts", "// NOTE: This file should not be edited"],
]) {
  test(`generator churn does not alter source identity: ${file}`, async (t) => {
    const r = await setup(t);
    const before = await r.hashBenchmarkInputs();
    await r.write(file, content);
    assert.equal(await r.hashBenchmarkInputs(), before);
    await r.write(file, content + "\n// regenerated");
    assert.equal(await r.hashBenchmarkInputs(), before);
    await fs.unlink(path.join(r.directory, file));
    assert.equal(await r.hashBenchmarkInputs(), before);
  });
}

test("output snapshots retain exact hashes without changing any file", async (t) => {
  const r = await setup(t);
  const before = await inspectGeneratedOutputs(r.directory);
  const file = "apps/farm/src/farm.d.ts";
  const contents = "/** Generated by Farm.js. Do not edit. */";
  assert.equal(before[file], null);
  await r.write(file, contents);
  const after = await inspectGeneratedOutputs(r.directory);
  assert.equal(after[file], createHash("sha256").update(contents).digest("hex"));
  assert.equal(await fs.readFile(path.join(r.directory, file), "utf8"), contents);
});

test("refuses a handwritten file occupying a reserved generated path", async (t) => {
  const r = await setup(t);
  await r.write("apps/farm/src/farm.d.ts", "export type MyHandwrittenType = string;");
  await assert.rejects(inspectGeneratedOutputs(r.directory), /unrecognized file/);
});

test("refuses non-file generated outputs", async (t) => {
  const r = await setup(t);
  await fs.mkdir(path.join(r.directory, "apps/farm/src/farm.d.ts"));
  await assert.rejects(inspectGeneratedOutputs(r.directory), /regular file/);
});

test("refuses a generated-output symlink without following it", async (t) => {
  const r = await setup(t);
  const target = path.join(r.directory, "elsewhere");
  await fs.mkdir(target);
  await fs.symlink(
    target,
    path.join(r.directory, "apps/farm/src/farm.d.ts"),
    process.platform === "win32" ? "junction" : "dir",
  );
  await assert.rejects(inspectGeneratedOutputs(r.directory), /regular file/);
});

test("mid-run guard accepts output churn but rejects every source identity change", () => {
  const start = source.indexOf("function assertRunIdentityUnchanged(");
  const end = source.indexOf("function assertPublishableRunIdentity(", start);
  assert.ok(start > 0 && end > start);
  const guard = new Function(source.slice(start, end) + "; return assertRunIdentityUnchanged;")();
  const identity = {
    benchmarkInputsDirty: false,
    commit: "revision",
    branch: "branch",
    farmSourceDirty: false,
    farmSourceDiffSha256: "source",
    rootLockDirty: false,
    rootLockSha256: "lock",
    inputSha256: "inputs",
  };
  guard(
    { ...identity, generatedOutputs: { file: null } },
    { ...identity, generatedOutputs: { file: "generated" } },
  );
  for (const key of Object.keys(identity)) {
    assert.throws(
      () => guard(identity, { ...identity, [key]: "changed" }),
      /Benchmark inputs changed/,
    );
  }
});

test("Git dirtiness ignores only exact generated outputs, not authored changes", async (t) => {
  const r = await setup(t);
  const git = (...args) => execFileSync("git", args, { cwd: r.directory, encoding: "utf8" });
  git("init", "--quiet");
  await r.write("apps/farm/src/farm.d.ts", "/** Generated by Farm.js. Do not edit. */");
  git("add", ".");
  git(
    "-c",
    "user.name=Benchmark Test",
    "-c",
    "user.email=benchmark@example.invalid",
    "-c",
    "commit.gpgsign=false",
    "commit",
    "--quiet",
    "-m",
    "fixture",
  );
  await r.write(
    "apps/farm/src/farm.d.ts",
    "/** Generated by Farm.js. Do not edit. */\n// regenerated",
  );
  await r.write("apps/next/next-env.d.ts", "// NOTE: This file should not be edited");
  const status = () => git("status", "--porcelain", "--", ".", ...generatedOutputExclusions("."));
  assert.equal(status(), "");
  await r.write("apps/farm/src/farm-custom.d.ts", "export type UserType = string;");
  assert.match(status(), /farm-custom\.d\.ts/);
  await r.write("pnpm-lock.yaml", "changed dependencies");
  assert.match(status(), /pnpm-lock\.yaml/);
});

for (const file of [
  "apps/farm/src/app/page.tsx",
  "apps/farm/farm.config.ts",
  "pnpm-lock.yaml",
  "apps/farm/src/farm-custom.d.ts",
  "apps/farm/src/handwritten.generated.ts",
  "apps/tanstack/src/routes/index.tsx",
  "apps/next/next.config.ts",
]) {
  test(`authored input remains fingerprinted: ${file}`, async (t) => {
    const r = await setup(t);
    const before = await r.hashBenchmarkInputs();
    await r.write(file, "changed input");
    assert.notEqual(await r.hashBenchmarkInputs(), before);
  });
}
