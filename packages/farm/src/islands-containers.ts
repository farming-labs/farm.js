/**
 * Islands mode (RFC 0006): a client component in a position that cannot hold `<f-island>` (a row
 * in a `<table>`, an `<option>` in a `<select>`, a shape in an `<svg>`, an `<li>` in a `<ul>`)
 * makes the element around it the island instead. The server module wraps that element in
 * `FarmIslandContainer`, a client component that renders its children. islx sends those children
 * as a server tree and the browser rebuilds them in the container's React root, so the client
 * components inside are its descendants and the browser gets the same elements as under React
 * Server Components: `ul > li`, a table the parser keeps whole, real `<option>` and SVG children.
 */
import fs from "node:fs";
import path from "node:path";
import { parseAst } from "rolldown/parseAst";
import { FARM_CLIENT_REFERENCE_PRAGMA } from "./islands-package-references";
import { memoizeInFarmSourceSnapshot } from "./utils/source-snapshot";

type AstNode = Record<string, any>;

/** The export a server module renders around a container. */
export const FARM_ISLAND_CONTAINER_EXPORT = "FarmIslandContainer";

const CONTAINER_LOCAL = "__FarmIslandContainer__";

/**
 * Elements whose children the HTML parser or CSS ties to their parent: the parser moves or drops
 * a custom element placed inside a table, a select or an svg, and `ul > li` selectors and list
 * numbering stop matching an `<li>` inside one.
 */
const ISLAND_CONTAINER_TAGS = new Set([
  "table",
  "thead",
  "tbody",
  "tfoot",
  "tr",
  "select",
  "optgroup",
  "datalist",
  "svg",
  "ul",
  "ol",
]);

/** Elements inside a container whose content is ordinary flow content again. */
const FLOW_CONTENT_TAGS = new Set(["td", "th", "caption", "foreignObject", "li"]);

/** Where Farm writes the container's client module. */
export function farmIslandContainerReferencePath(root: string): string {
  return path.join(root, ".farm", "client-references", "farm.js+core", "__island-container.tsx");
}

/** Writes the container's client module (an unchanged file stays as it is) and returns its path. */
export function ensureFarmIslandContainerReference(root: string): string {
  const file = farmIslandContainerReferencePath(root);
  const source = [
    "// Generated by Farm: the island around an element whose children are client components (RFC 0006).",
    FARM_CLIENT_REFERENCE_PRAGMA,
    '"use client";',
    `export function ${FARM_ISLAND_CONTAINER_EXPORT}({ children }: { children?: unknown }) {`,
    "  return children as never;",
    "}",
    "",
  ].join("\n");
  let current: string | null = null;
  try {
    current = fs.readFileSync(file, "utf8");
  } catch {
    // Not written yet.
  }
  if (current !== source) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, source);
  }
  return file;
}

function parse(code: string, file: string): AstNode | null {
  const extension = path.extname(file).slice(1);
  const lang =
    extension === "ts" || extension === "mts" || extension === "cts"
      ? "ts"
      : extension === "js" || extension === "mjs" || extension === "cjs" || extension === "jsx"
        ? "jsx"
        : "tsx";
  return memoizeInFarmSourceSnapshot(`ast:${lang}`, code, () => {
    try {
      return parseAst(code, { lang: lang as "tsx" }) as unknown as AstNode;
    } catch {
      return null;
    }
  });
}

function jsxName(node: AstNode | undefined): string | null {
  if (!node) return null;
  if (node.type === "JSXIdentifier") return node.name as string;
  if (node.type === "JSXMemberExpression") {
    // `<Parts.Row />` renders the namespace binding's member.
    let object = node.object as AstNode;
    while (object.type === "JSXMemberExpression") object = object.object;
    return object.type === "JSXIdentifier" ? (object.name as string) : null;
  }
  return null;
}

export interface FarmIslandContainer {
  tag: string;
  start: number;
  end: number;
}

/**
 * The outermost container elements in `code` that hold a use of one of `bindings` (the module's
 * client components, and server components that render client components) as content the parser
 * or CSS ties to them. Null when the module does not parse.
 */
export function findFarmIslandContainers(
  code: string,
  file: string,
  bindings: readonly string[],
): FarmIslandContainer[] | null {
  if (bindings.length === 0) return [];
  // Cheap check first: no container tag, nothing to wrap.
  if (!/<(?:table|thead|tbody|tfoot|tr|select|optgroup|datalist|svg|ul|ol)[\s>/]/.test(code)) {
    return [];
  }
  const program = parse(code, file);
  if (!program) return null;
  const names = new Set(bindings);
  const found = new Map<number, FarmIslandContainer>();
  // Host elements from the root to the current node, outermost first.
  const open: AstNode[] = [];

  const visit = (node: unknown): void => {
    if (!node || typeof node !== "object") return;
    if (Array.isArray(node)) {
      for (const child of node) visit(child);
      return;
    }
    const current = node as AstNode;
    if (typeof current.type !== "string") return;
    if (current.type === "JSXElement") {
      const name = jsxName(current.openingElement?.name);
      if (name && names.has(name)) {
        // The outermost container since the innermost flow-content cell.
        let container: AstNode | undefined;
        for (let depth = open.length - 1; depth >= 0; depth--) {
          const tag = jsxName(open[depth]!.openingElement.name)!;
          if (FLOW_CONTENT_TAGS.has(tag)) break;
          if (ISLAND_CONTAINER_TAGS.has(tag)) container = open[depth];
        }
        if (container && !found.has(container.start)) {
          found.set(container.start, {
            tag: jsxName(container.openingElement.name)!,
            start: container.start,
            end: container.end,
          });
        }
      }
      const host =
        current.openingElement?.name?.type === "JSXIdentifier" &&
        (ISLAND_CONTAINER_TAGS.has(name!) || FLOW_CONTENT_TAGS.has(name!));
      if (host) open.push(current);
      visit(current.openingElement?.attributes);
      visit(current.children);
      if (host) open.pop();
      return;
    }
    for (const [key, value] of Object.entries(current)) {
      if (key === "start" || key === "end" || key === "loc" || key === "range") continue;
      if (value && typeof value === "object") visit(value);
    }
  };
  visit(program);

  // Only the outermost: a container inside another one grows with it.
  const sorted = [...found.values()].sort((a, b) => a.start - b.start);
  const outermost: FarmIslandContainer[] = [];
  for (const container of sorted) {
    const last = outermost[outermost.length - 1];
    if (last && container.start >= last.start && container.end <= last.end) continue;
    outermost.push(container);
  }
  return outermost;
}

/**
 * Wraps each container in `code` that holds one of `bindings` in `FarmIslandContainer`, imported
 * from `reference`. Null when there is nothing to wrap.
 */
export function wrapFarmIslandContainers(options: {
  code: string;
  file: string;
  bindings: readonly string[];
  reference: string;
}): string | null {
  const containers = findFarmIslandContainers(options.code, options.file, options.bindings);
  if (!containers || containers.length === 0) return null;
  let code = options.code;
  for (const container of [...containers].reverse()) {
    code =
      code.slice(0, container.start) +
      `<${CONTAINER_LOCAL}>` +
      code.slice(container.start, container.end) +
      `</${CONTAINER_LOCAL}>` +
      code.slice(container.end);
  }
  const specifier = JSON.stringify(options.reference.split(path.sep).join("/"));
  const declaration = `import { ${FARM_ISLAND_CONTAINER_EXPORT} as ${CONTAINER_LOCAL} } from ${specifier};\n`;
  // After the directive prologue, which must stay first.
  let prologueEnd = 0;
  for (const statement of (parse(options.code, options.file)?.body ?? []) as AstNode[]) {
    if (statement.type !== "ExpressionStatement" || typeof statement.directive !== "string") break;
    prologueEnd = statement.end;
  }
  if (prologueEnd === 0) return declaration + code;
  return `${code.slice(0, prologueEnd)}\n${declaration}${code.slice(prologueEnd)}`;
}
