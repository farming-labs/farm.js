// @vitest-environment node

import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";
import type { FarmUserConfig } from "../config";
import { loadFarmMobileRuntime } from "../config-runtime";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const roots: string[] = [];
afterEach(async () => {
  await Promise.all(roots.splice(0).map((root) => fs.rm(root, { recursive: true, force: true })));
});

const LAYOUT = "export default function Layout({ children }) { return children; }\n";

async function createApp(files: Record<string, string>): Promise<string> {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "farm-mobile-port-"));
  roots.push(root);
  for (const [file, contents] of Object.entries({
    "package.json": JSON.stringify({ name: "notes" }),
    "src/app/layout.tsx": LAYOUT,
    ...files,
  })) {
    await fs.mkdir(path.dirname(path.join(root, file)), { recursive: true });
    await fs.writeFile(path.join(root, file), contents);
  }
  return root;
}

function userConfig(native: object = { auto: "on" }): FarmUserConfig {
  return {
    telemetry: false,
    mobile: { id: "com.example.notes", server: "https://notes.example.com", native },
  };
}

async function generate(root: string, config = userConfig(), os?: "android" | "ios") {
  const { generateFarmMobileRoutes } = await loadFarmMobileRuntime();
  return generateFarmMobileRoutes({ root, userConfig: config, analyze: true, os });
}

const ports = (root: string, file = "") => path.join(root, ".farm/output/mobile/ports", file);

const PACKING = `"use client";
import { Link } from "@farm.js/core/client";
import { useState } from "react";

export default function Packing() {
  const [items, setItems] = useState(["Map"]);
  const [draft, setDraft] = useState("");
  return (
    <div style={{ display: "flex", flexDirection: "column", gap: 12 }}>
      <input value={draft} onChange={(event) => setDraft(event.target.value)} />
      <button onClick={() => setItems([...items, draft])}>Add</button>
      <ul>{items.map((item) => <li key={item}>{item}</li>)}</ul>
      <Link href="/">Home</Link>
    </div>
  );
}
`;

describe("React Native ports", () => {
  it("ports the example's packing list, renaming only its elements", async () => {
    const example = path.join(packageRoot, "../../examples/mobile/src/app/lab/packing/page.tsx");
    const root = await createApp({
      "src/app/lab/packing/page.tsx": await fs.readFile(example, "utf8"),
    });
    const result = await generate(root);
    expect(result.screens["/lab/packing"]).toMatchObject({
      screen: "native",
      source: "analyzer",
      module: "app/lab/packing",
      file: ".farm/output/mobile/ports/app/lab/packing.port.tsx",
    });
    expect(result.warnings).toEqual([]);
    const page = await fs.readFile(ports(root, "src/app/lab/packing/page.tsx"), "utf8");
    // "use client" stays first; Link comes from the elements runtime, not core.
    expect(page).toMatch(
      /^\/\/ Generated by Farm from src\/app\/lab\/packing\/page\.tsx[^\n]*\n"use client";\n\nimport \{ FarmDom as __FarmDom, Link as __FarmLink \} from "@farm\.js\/native\/elements";\n/,
    );
    expect(page).not.toContain("@farm.js/core");
    expect(page).toContain(
      '<__FarmDom.input\n        value={draft}\n        placeholder="Add an item"\n        onChange={(event) => setDraft(event.target.value)}',
    );
    expect(page).toContain('<__FarmLink href="/" style={{ color: "#1f6f43" }}>');
    expect(page).toContain("</__FarmDom.ul>");
    // Everything but the elements is the page as written.
    const original = await fs.readFile(example, "utf8");
    const strip = (source: string) =>
      source
        .replace(/^\/\/ Generated by Farm[^\n]*\n/, "")
        .replace(/import \{ FarmDom[^\n]*\n/, "")
        .replace(/import \{ Link \} from "@farm\.js\/core\/client";/, "")
        .replaceAll("__FarmDom.", "")
        .replaceAll("__FarmLink", "Link");
    expect(strip(page)).toBe(
      original.replace(/import \{ Link \} from "@farm\.js\/core\/client";/, ""),
    );
    expect(await fs.readFile(ports(root, "app/lab/packing.port.tsx"), "utf8")).toBe(
      [
        "// Generated by Farm: the React Native port of src/app/lab/packing/page.tsx. Do not edit.",
        'import { useRouteParams } from "@farm.js/native";',
        'import { FarmDomScreen } from "@farm.js/native/elements";',
        'import Page from "../../src/app/lab/packing/page";',
        "",
        "// The app's CSS for each element the page renders, light and dark.",
        "const sheet = {};",
        "",
        "export default function FarmPort() {",
        "  return (",
        "    <FarmDomScreen sheet={sheet}>",
        "      <Page params={useRouteParams()} />",
        "    </FarmDomScreen>",
        "  );",
        "}",
        "",
      ].join("\n"),
    );
  });

  it("copies app components with JSX and imports other modules where they are", async () => {
    const root = await createApp({
      "src/app/notes/page.tsx": `"use client";
import { useState } from "react";
import { Row } from "@/components/row";
import { initialNotes, type Note } from "../../lib/notes";
export const metadata = { title: "Notes" };
export default function Notes() {
  const [notes] = useState<Note[]>(initialNotes);
  return <ul>{notes.map((note) => <li key={note.id}><Row note={note} /></li>)}</ul>;
}
`,
      "src/components/row.tsx": `import type { Note } from "../lib/notes";
export function Row({ note }: { note: Note }) {
  return <p onClick={() => console.log(note.id)}>{note.title}</p>;
}
`,
      "src/lib/notes.ts": `export interface Note { id: string; title: string }
export const initialNotes: Note[] = [{ id: "1", title: "Creek" }];
`,
    });
    const result = await generate(root);
    expect(result.screens["/notes"]).toMatchObject({ screen: "native", source: "analyzer" });
    const page = await fs.readFile(ports(root, "src/app/notes/page.tsx"), "utf8");
    // The alias points at the copied component; the plain module stays where it is.
    expect(page).toContain('import { Row } from "../../components/row";');
    expect(page).toContain('from "../../../../../../../src/lib/notes";');
    const row = await fs.readFile(ports(root, "src/components/row.tsx"), "utf8");
    expect(row).toContain("<__FarmDom.p onClick=");
    await expect(fs.stat(ports(root, "src/lib/notes.ts"))).rejects.toThrow();
    expect(await fs.readFile(ports(root, "app/notes.port.tsx"), "utf8")).toContain(
      'export { metadata } from "../src/app/notes/page";',
    );
  });

  it("keeps a route web, with the reason, when the port needs what it cannot emit yet", async () => {
    const root = await createApp({
      "src/app/routed/page.tsx": `"use client";
import { useState } from "react";
import { useRouter } from "@farm.js/core/client";
export default function Routed() {
  const [draft, setDraft] = useState("");
  const router = useRouter();
  return <input value={draft} onChange={(event) => setDraft(router.pathname + event.target.value)} />;
}
`,
      "src/app/themed/page.tsx": `"use client";
import { createContext, useContext, useState } from "react";
const Theme = createContext("light");
export default function Themed() {
  const [draft, setDraft] = useState("");
  const theme = useContext(Theme);
  return <input value={draft + theme} onChange={(event) => setDraft(event.target.value)} />;
}
`,
    });
    const result = await generate(root);
    expect(result.screens["/routed"]).toMatchObject({ screen: "web", requested: "native" });
    expect(result.screens["/themed"]).toMatchObject({ screen: "web", requested: "native" });
    expect(result.warnings).toEqual([
      expect.stringContaining(
        '"/routed" is portable, but Farm cannot port it yet, so it stays web: src/app/routed/page.tsx:3:10 uses useRouter from "@farm.js/core/client", which ports do not map yet',
      ),
      expect.stringContaining(
        'src/app/themed/page.tsx:2:25 uses useContext from "react", which ports do not support yet',
      ),
    ]);
    await expect(fs.stat(ports(root))).rejects.toThrow();
  });

  it("ports only for Android, only when asked, and removes ports it no longer makes", async () => {
    const root = await createApp({ "src/app/page.tsx": PACKING });
    expect((await generate(root, userConfig(), "ios")).screens["/"]).toMatchObject({
      screen: "web",
      requested: "native",
    });
    await generate(root);
    await fs.stat(ports(root, "app.port.tsx"));
    // `auto: "report"` ports nothing, and the stale files go.
    expect((await generate(root, userConfig({ auto: "report" }))).screens["/"]).toMatchObject({
      screen: "web",
      source: "default",
    });
    await expect(fs.stat(ports(root))).rejects.toThrow();
    // A config route that asks for a native screen gets the port without `auto: "on"`.
    const asked = await generate(root, userConfig({ routes: { "/": { screen: "native" } } }));
    expect(asked.screens["/"]).toMatchObject({ screen: "native", source: "config" });
    expect(asked.warnings).toEqual([]);
  });

  it("applies the app's CSS for each element, which every page links in production", async () => {
    const root = await createApp({
      "src/app/(styled)/layout.tsx": `import "../globals.css";
export default function Styled({ children }) { return <main className="page">{children}</main>; }
`,
      "src/app/(styled)/about/page.tsx":
        "export default function About() { return <p>About</p>; }\n",
      "src/app/globals.css": `:root { --text: #1c1f1d; font-family: system-ui; }
@media (prefers-color-scheme: dark) { :root { --text: #e8ebe7; } }
* { box-sizing: border-box; }
body { margin: 0; color: var(--text); }
h1 { font-size: 24px; }
input { font: inherit; color: var(--text); }
.list li + li { border-top: 1px solid #ddd; }
`,
      "src/app/lab/page.tsx": PACKING.replace("<input", "<h1>Packing</h1><input"),
    });
    const result = await generate(root);
    // The lab layout never imports globals.css, but the production bundle links it on every page.
    expect(result.screens["/lab"]).toMatchObject({ screen: "native", source: "analyzer" });
    const entry = await fs.readFile(ports(root, "app/lab.port.tsx"), "utf8");
    const sheet = JSON.parse(/const sheet = (.*);/.exec(entry)![1]!);
    expect(sheet).toEqual({
      // system-ui is the system's sans-serif.
      html: { style: { fontFamily: "sans" } },
      body: {
        style: { marginTop: 0, marginRight: 0, marginBottom: 0, marginLeft: 0, color: "#1c1f1d" },
        dark: { color: "#e8ebe7" },
      },
      h1: { style: { fontSize: 24 } },
      // Form controls take a font from their parent only when the CSS says so.
      input: {
        style: { color: "#1c1f1d" },
        dark: { color: "#e8ebe7" },
        inherit: ["fontFamily", "fontSize", "fontStyle", "fontWeight", "lineHeight"],
      },
    });
  });

  it("keeps a route web when the app's CSS depends on where an element renders", async () => {
    const page = `"use client";
import { useState } from "react";
export default function Lab() {
  const [items] = useState(["a"]);
  return <main><h1>Lab</h1><ul>{items.map((item) => <li key={item}>{item}</li>)}</ul></main>;
}
`;
    const root = await createApp({
      // The stylesheet comes from another route group's layout; the root layout's class wraps /lab.
      "src/app/layout.tsx": `export default function Layout({ children }) { return <div className="p-4">{children}</div>; }
`,
      "src/app/(site)/layout.tsx": `import "../app.css";
export default function Site({ children }) { return children; }
`,
      "src/app/(site)/about/page.tsx": "export default function About() { return <p>About</p>; }\n",
      "src/app/app.css": `main h1 { color: red; }
.p-4 li { padding: 4px; }
.other li { padding: 8px; }
`,
      "src/app/lab/page.tsx": page,
    });
    const result = await generate(root);
    expect(result.screens["/lab"]).toMatchObject({ screen: "web", requested: "native" });
    // `.other` is on no layout, so its rule never matches; `.p-4` wraps the page on the web.
    expect(result.warnings).toEqual([
      expect.stringMatching(
        /"\/lab" is portable, but Farm cannot port it yet, so it stays web: "main h1" depends on where <h1> renders; "\.p-4 li" depends on where <li> renders\.$/,
      ),
    ]);

    const tailwind = await createApp({
      "src/app/(site)/layout.tsx": `import "../app.css";\nexport default function Site({ children }) { return children; }\n`,
      "src/app/(site)/about/page.tsx": "export default function About() { return <p>About</p>; }\n",
      "src/app/app.css": `@import "tailwindcss";\n@utility tab-4 { tab-size: 4; }\n`,
      "src/app/lab/page.tsx": page,
    });
    // A custom utility changes what classes mean, which the native style table does not know.
    expect((await generate(tailwind)).warnings).toEqual([
      expect.stringContaining("src/app/app.css uses @utility, which ports do not read yet"),
    ]);
  });

  it("ports Tailwind pages: preflight, utilities, and the app's own classes", async () => {
    const root = await createApp({
      "src/app/layout.tsx": `import "./globals.css";
export default function Layout({ children }) { return <div className="min-h-screen">{children}</div>; }
`,
      "src/app/globals.css": `@import "tailwindcss";
@source "../components";
.card { padding: 12px; border-radius: 8px; }
.card p { color: #555; }
`,
      "src/app/notes/notes.css": ".note { margin: 0; }\n",
      "src/app/notes/page.tsx": `"use client";
import { useState } from "react";
import { Link } from "@farm.js/core/client";
import "./notes.css";
export default function Notes() {
  const [notes] = useState(["Creek"]);
  return (
    <main className="flex flex-col gap-4 p-4">
      <h1 className="text-2xl font-bold dark:text-white">Notes</h1>
      <ul>{notes.map((note) => <li key={note} className="card bg-white">{note}</li>)}</ul>
      <Link className="text-blue-600 underline" href="/">Home</Link>
    </main>
  );
}
`,
    });
    const result = await generate(root);
    expect(result.warnings).toEqual([]);
    expect(result.screens["/notes"]).toMatchObject({ screen: "native", source: "analyzer" });
    const page = await fs.readFile(ports(root, "src/app/notes/page.tsx"), "utf8");
    // The page's CSS import goes: its rules reach the port through the sheet.
    expect(page).not.toContain("notes.css");
    // The JSON after an element's `__farm={`, read up to its matching brace.
    const resolved = (tag: string) => {
      const start = page.indexOf("__farm={", page.indexOf(`<${tag} `)) + "__farm={".length;
      let depth = 0;
      let end = start;
      do {
        if (page[end] === "{") depth += 1;
        else if (page[end] === "}") depth -= 1;
        end += 1;
      } while (depth > 0);
      return JSON.parse(page.slice(start, end));
    };
    expect(resolved("__FarmDom.h1")).toEqual({
      tw: {
        style: { fontSize: 24, lineHeight: 32, fontWeight: 700 },
        dark: { color: "#ffffff" },
      },
      css: { style: {} },
    });
    // `card` is the app's class, after the bg-white utility.
    expect(resolved("__FarmDom.li")).toEqual({
      tw: { style: { backgroundColor: "#ffffff" } },
      css: {
        style: {
          paddingTop: 12,
          paddingRight: 12,
          paddingBottom: 12,
          paddingLeft: 12,
          borderTopLeftRadius: 8,
          borderTopRightRadius: 8,
          borderBottomRightRadius: 8,
          borderBottomLeftRadius: 8,
        },
      },
    });
    expect(resolved("__FarmLink").tw.style).toMatchObject({ color: "#155dfc" });
    expect(await fs.readFile(ports(root, "app/notes.port.tsx"), "utf8")).toContain(
      "<FarmDomScreen sheet={sheet} preflight>",
    );

    // With Tailwind loaded, a class nothing styles may be a utility the table does not know; a
    // class rule that depends on structure cannot be decided. Both keep the route web.
    await fs.writeFile(
      path.join(root, "src/app/notes/page.tsx"),
      (await fs.readFile(path.join(root, "src/app/notes/page.tsx"), "utf8"))
        .replace('"flex flex-col gap-4 p-4"', '"flex flex-col gap-4 p-4 ghost"')
        .replace(
          '<li key={note} className="card bg-white">{note}</li>',
          '<li key={note} className="card"><p>{note}</p></li>',
        ),
    );
    const blocked = await generate(root);
    expect(blocked.screens["/notes"]).toMatchObject({ screen: "web", requested: "native" });
    expect(blocked.warnings[0]).toContain('class "ghost"');
    expect(blocked.warnings[0]).toContain('".card p" depends on where <p> renders');
  });

  it("resolves classes against the app's @theme, with dark values from :root", async () => {
    const root = await createApp({
      "src/app/layout.tsx": `import "./globals.css";\nexport default function Layout({ children }) { return children; }\n`,
      "src/app/globals.css": `@import "tailwindcss";
:root { --surface: #ffffff; }
@media (prefers-color-scheme: dark) { :root { --surface: #1d211e; } }
@theme inline {
  --color-surface: var(--surface);
  --color-brand: oklch(52.7% 0.154 150.069);
  --radius-card: 12px;
}
`,
      "src/app/page.tsx": PACKING.replace(
        "<button onClick",
        '<button className="bg-brand rounded-card" onClick',
      ).replace("<ul>", '<ul className="bg-surface">'),
    });
    const result = await generate(root);
    expect(result.warnings).toEqual([]);
    const page = await fs.readFile(ports(root, "src/app/page.tsx"), "utf8");
    expect(page).toContain(
      // The theme's oklch brand color, converted as Tailwind's own green-700 is.
      '<__FarmDom.button __farm={{"tw":{"style":{"borderTopLeftRadius":12,"borderTopRightRadius":12,"borderBottomRightRadius":12,"borderBottomLeftRadius":12,"backgroundColor":"#008236"}},"css":{"style":{}}}}',
    );
    expect(page).toContain(
      '<__FarmDom.ul __farm={{"tw":{"style":{"backgroundColor":"#ffffff"},"dark":{"backgroundColor":"#1d211e"}},"css":{"style":{}}}}>',
    );
  });
});
