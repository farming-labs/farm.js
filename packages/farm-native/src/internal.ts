/**
 * `@farm.js/native/internal`: shell calls for Farm's own packages, such as `@farm.js/auth/client`
 * on native screens. Internal: not a public API, and it can change in any release. Apps sign in
 * with `signIn` and `signUp` from `@farm.js/auth/client`.
 */
import { farmShell } from "./runtime";

/** What the shell answers for a native sign-in: the auth route's status and body, no cookies. */
export interface FarmShellSignInReply {
  status: number;
  body: string;
}

/**
 * POST `body` as JSON to `path` (such as `/api/auth/sign-in/email`) from the shell's native code,
 * which sends it only to `mobile.server`, only under `auth.basePath`, and follows no redirect. On
 * success the shell keeps the session cookie in the WebView and issues the device token before
 * this resolves. Rejects when the shell is missing or older, the server is unreachable, or the
 * device token was not issued.
 * @internal
 */
export async function shellSignIn(path: string, body: unknown): Promise<FarmShellSignInReply> {
  const shell = farmShell();
  if (typeof shell?.signIn !== "function") {
    throw new Error(
      "Native sign-in needs the Farm mobile shell generated by this version of @farm.js/mobile " +
        "(farm dev --mobile or farm build --mobile).",
    );
  }
  const reply = await shell.signIn(path, JSON.stringify(body ?? {}));
  return { status: Number(reply.status), body: String(reply.body ?? "") };
}
