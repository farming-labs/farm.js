describe("resolveFarmReactNative", () => {
  it("reads the React Native and Hermes versions, and rejects versions before 0.88", async () => {
    const root = await tempDir();
    await writePackage(root, { name: "app" });
    const dir = path.join(root, "node_modules", "react-native");
    await writePackage(
      dir,
      { name: "react-native", version: "0.88.1" },
      {
        "sdks/hermes-engine/version.properties": "HERMES_VERSION_NAME=260318099.0.5\n",
      },
    );
    expect(resolveFarmReactNative(root)).toEqual({
      version: "0.88.1",
      hermesVersion: "260318099.0.5",
      dir,
    });
    await writePackage(dir, { name: "react-native", version: "0.86.3" });
    expect(() => resolveFarmReactNative(root)).toThrow(/0\.86\.3 is older than 0\.88\.0/);
  });
});

describe("resolveWatchFolders", () => {
  it("watches only the store packages a screen bundle can reach, not the whole workspace", async () => {
    const workspace = await tempDir();
    const store = path.join(workspace, "node_modules", ".pnpm");
    const app = path.join(workspace, "apps", "mobile");
    const pkg = (name: string) =>
      path.join(store, `${name.replace("/", "+")}@1.0.0`, "node_modules", name);
    await writePackage(pkg("react"), { name: "react" });
    await writePackage(pkg("react-native"), {
      name: "react-native",
      dependencies: { "@react-native/virtualized-lists": "1", metro: "1" },
      peerDependencies: { react: "1" },
    });
    await writePackage(pkg("@react-native/virtualized-lists"), {
      name: "@react-native/virtualized-lists",
    });
    await writePackage(pkg("metro"), { name: "metro", dependencies: { "@babel/core": "1" } });
    await writePackage(pkg("vite"), { name: "vite" });
    await writePackage(pkg("zod"), { name: "zod" });
    const link = async (from: string, name: string) => {
      const at = path.join(from, "node_modules", name);
      await mkdir(path.dirname(at), { recursive: true });
      await symlink(pkg(name), at, "junction");
    };
    await writePackage(app, {
      name: "mobile",
      dependencies: { zod: "1", "@farm.js/core": "1" },
      devDependencies: { "react-native": "1", vite: "1" },
    });
    for (const name of ["react", "react-native", "zod", "vite"]) await link(app, name);
    const rnStore = path.dirname(pkg("react-native"));
    await link(rnStore.replace(/node_modules$/, ""), "react");
    await link(rnStore.replace(/node_modules$/, ""), "@react-native/virtualized-lists");
    await link(rnStore.replace(/node_modules$/, ""), "metro");

    const folders = resolveWatchFolders(app);
    // The node_modules holding each package, so pnpm's links to its dependencies are watched too.
    expect(folders).toEqual([
      app,
      ...["@react-native+virtualized-lists", "react", "react-native", "zod"]
        .map((entry) => path.join(store, `${entry}@1.0.0`, "node_modules"))
        .sort(),
    ]);
    // Build tools and web-only packages stay out.
    expect(folders.join("\n")).not.toMatch(/metro|vite|farm\.js/);
  });
});

describe("farmNativeBundleFiles", () => {
  it("keeps build bundles out of the way of the dev entry's platform resolution", () => {
    const outDir = path.join("/app", ".farm", "output", "mobile", "native");
    const { js, bytecode } = farmNativeBundleFiles(outDir, "android");
    // Metro would resolve the entry `index` to `index.android.js` in that directory.
    for (const file of [js, bytecode]) {
      expect(path.dirname(file)).not.toBe(outDir);
      expect(path.basename(file)).not.toMatch(/^index\./);
    }
    expect(js).toBe(path.join(outDir, "build", "android.js"));
    expect(bytecode).toBe(path.join(outDir, "build", "android.hbc"));
  });
});

describe("closeWithConnections", () => {
  it("closes even while a client holds an upgraded socket, as the debug app does with Metro", async () => {
    const server = createServer();
    server.on("upgrade", (_request, socket) => {
      socket.write(
        "HTTP/1.1 101 Switching Protocols\r\nUpgrade: websocket\r\nConnection: Upgrade\r\n\r\n",
      );
    });
    const close = closeWithConnections(server);
    await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
    const { port } = server.address() as { port: number };
    const client = connect(port, "127.0.0.1");
    await new Promise<void>((resolve) => {
      client.once("data", () => resolve());
      client.write(
        "GET /hot HTTP/1.1\r\nHost: x\r\nUpgrade: websocket\r\nConnection: Upgrade\r\n\r\n",
      );
    });
    const closed = await Promise.race([
      close().then(() => "closed"),
      new Promise((resolve) => setTimeout(() => resolve("hung"), 2000)),
    ]);
    client.destroy();
    expect(closed).toBe("closed");
  });
});

describe("resolveSingletonsFromApp", () => {
  it("resolves react and react-native from the app for every importer, and nothing else", () => {
    const calls: Array<[string, string]> = [];
    const resolve = (context: { originModulePath: string }, moduleName: string) => {
      calls.push([moduleName, context.originModulePath]);
      return { type: "sourceFile", filePath: moduleName };
    };
    const resolveRequest = resolveSingletonsFromApp("/app", resolve);
    const linked = { originModulePath: "/repo/packages/farm-native/dist/register.js" };
    resolveRequest(linked, "react-native", "android");
    resolveRequest(linked, "react/jsx-runtime", "android");
    resolveRequest(linked, "react-native-svg", "android");
    resolveRequest(linked, "./routes", "android");
    expect(calls).toEqual([
      ["react-native", path.join("/app", "package.json")],
      ["react/jsx-runtime", path.join("/app", "package.json")],
      ["react-native-svg", linked.originModulePath],
      ["./routes", linked.originModulePath],
    ]);
  });
});
