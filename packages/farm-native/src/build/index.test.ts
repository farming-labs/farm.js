import { mkdir, mkdtemp, rm, symlink, writeFile } from "node:fs/promises";
import { realpathSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { createServer } from "node:http";
import { connect } from "node:net";
import {
  closeWithConnections,
  createFarmNativeEntry,
  farmNativeBundleFiles,
  resolveFarmReactNative,
  resolveSingletonsFromApp,
  resolveWatchFolders,
} from "./index";

const roots: string[] = [];
afterEach(async () => {
  await Promise.all(roots.splice(0).map((root) => rm(root, { recursive: true, force: true })));
});

async function tempDir(): Promise<string> {
  const root = realpathSync(await mkdtemp(path.join(os.tmpdir(), "farm-native-build-")));
  roots.push(root);
  return root;
}

async function writePackage(
  dir: string,
  manifest: Record<string, unknown>,
  files: Record<string, string> = {},
) {
  await mkdir(dir, { recursive: true });
  await writeFile(path.join(dir, "package.json"), JSON.stringify(manifest));
  for (const [file, contents] of Object.entries(files)) {
    await mkdir(path.dirname(path.join(dir, file)), { recursive: true });
    await writeFile(path.join(dir, file), contents);
  }
}

