/**
 * `@farm.js/native/build`: the React Native screen bundle for `farm dev|build --mobile`. Node only,
 * loaded by the CLI from the app when at least one route resolves to a React Native screen.
 *
 * One generated entry registers every screen under its manifest module id. Metro bundles it
 * (React Native's own bundler, which Fast Refresh and RN libraries are tested against), and
 * `hermesc` from the app's `react-native` compiles the build bundle to Hermes bytecode.
 */
import { spawn } from "node:child_process";
import { existsSync, readFileSync, realpathSync } from "node:fs";
import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";

/** One React Native screen: its module id, page route, and absolute source file. */
export interface FarmNativeScreen {
  module: string;
  route: string;
  file: string;
}

export interface FarmNativeEntryOptions {
  /** Absolute path the entry is written to; screen imports are relative to it. */
  entryFile: string;
  screens: readonly FarmNativeScreen[];
  /** The app's basePath ("" or "/base"). */
  basePath: string;
  locales?: readonly string[];
}

export interface FarmReactNative {
  /** The app's `react-native` version, which picks the Maven artifacts. */
  version: string;
  /** The Hermes version that version ships (`com.facebook.hermes:hermes-android`). */
  hermesVersion: string;
  /** The package directory. */
  dir: string;
}

/** The oldest React Native the shell's host code is written against. */
export const MIN_REACT_NATIVE = "0.88.0";

/** An expected failure with its own fix; the CLI prints it without a stack. */
function nativeError(message: string): Error {
  return Object.assign(new Error(message), { name: "FarmMobileError" });
}

function compareVersions(left: string, right: string): number {
  const a = left.split(/[.-]/).map(Number);
  const b = right.split(/[.-]/).map(Number);
  for (let index = 0; index < 3; index++) {
    const diff = (a[index] ?? 0) - (b[index] ?? 0);
    if (diff !== 0) return diff;
  }
  return 0;
}

const INSTALL_HINT =
  "Native screens need React Native and the Metro config next to @farm.js/native:\n" +
  "  pnpm add react-native@^0.88 @react-native/metro-config@^0.88 @farm.js/native";

/** The app's `react-native`, or an error that says how to install it. */
export function resolveFarmReactNative(root: string): FarmReactNative {
  let manifestFile: string;
  try {
    manifestFile = createRequire(path.join(root, "package.json")).resolve(
      "react-native/package.json",
    );
  } catch {
    throw nativeError(`page.native.tsx screens need react-native in ${root}.\n${INSTALL_HINT}`);
  }
  const dir = path.dirname(manifestFile);
  const { version } = JSON.parse(readFileSync(manifestFile, "utf8")) as { version: string };
  if (compareVersions(version, MIN_REACT_NATIVE) < 0) {
    throw nativeError(
      `react-native ${version} is older than ${MIN_REACT_NATIVE}, the first version Farm's ` +
        `Android host supports.\n${INSTALL_HINT}`,
    );
  }
  const hermes = readFileSync(
    path.join(dir, "sdks", "hermes-engine", "version.properties"),
    "utf8",
  ).match(/^HERMES_VERSION_NAME=(.+)$/m)?.[1];
  if (!hermes) throw nativeError(`Cannot read the Hermes version of react-native ${version}.`);
  return { version, hermesVersion: hermes.trim(), dir };
}

function importPath(from: string, file: string): string {
  const relative = path.relative(path.dirname(from), file).split(path.sep).join("/");
  return relative.startsWith(".") ? relative : `./${relative}`;
}

/**
 * The generated entry: registers every screen by module id with a lazy `require`, so a screen's
 * module runs the first time it opens.
 */
export function createFarmNativeEntry(options: FarmNativeEntryOptions): string {
  const screens = [...options.screens].sort((left, right) =>
    left.module < right.module ? -1 : left.module > right.module ? 1 : 0,
  );
  const lines = screens.map(
    (screen) =>
      `    ${JSON.stringify(screen.module)}: {\n` +
      `      route: ${JSON.stringify(screen.route)},\n` +
      `      load: () => require(${JSON.stringify(importPath(options.entryFile, screen.file))}),\n` +
      "    },",
  );
  return [
    "// Generated by @farm.js/native on every farm dev|build --mobile. Do not edit.",
    'import { registerFarmScreens } from "@farm.js/native/register";',
    "",
    "registerFarmScreens({",
    `  basePath: ${JSON.stringify(options.basePath === "/" ? "" : options.basePath)},`,
    ...(options.locales?.length ? [`  locales: ${JSON.stringify(options.locales)},`] : []),
    "  screens: {",
    ...lines,
    "  },",
    "});",
    "",
  ].join("\n");
}

type MetroConfig = Record<string, any>;

interface Toolchain {
  /** Modules Metro's React Native config injects into every bundle, as [from, package]. */
  runtimeSeeds: Array<[string, string]>;
  metro: any;
  devMiddleware: any;
  cliPlugin: any;
  metroConfig: any;
}

/** Metro and React Native's CLI plugin, resolved through the app's own react-native. */
function loadToolchain(root: string, reactNative: FarmReactNative): Toolchain {
  const fromApp = createRequire(path.join(root, "package.json"));
  let metroConfig: unknown;
  try {
    metroConfig = fromApp("@react-native/metro-config");
  } catch {
    throw nativeError(`page.native.tsx screens need @react-native/metro-config.\n${INSTALL_HINT}`);
  }
  const fromReactNative = createRequire(path.join(reactNative.dir, "package.json"));
  const pluginDir = path.dirname(
    fromReactNative.resolve("@react-native/community-cli-plugin/package.json"),
  );
  const fromPlugin = createRequire(path.join(pluginDir, "package.json"));
  const metroConfigDir = path.dirname(fromApp.resolve("@react-native/metro-config/package.json"));
  return {
    runtimeSeeds: [
      // Babel's helpers are imported by transformed code and resolved through hoisting.
      [reactNative.dir, "@babel/runtime"],
      [metroConfigDir, "@react-native/js-polyfills"],
      [metroConfigDir, "metro-runtime"],
    ],
    metroConfig,
    cliPlugin: fromReactNative("@react-native/community-cli-plugin"),
    metro: fromPlugin("metro"),
    devMiddleware: fromPlugin("@react-native/dev-middleware"),
  };
}

// Build tools that react-native and its Metro config depend on but no bundle imports. Their trees
// are most of a React Native install, and Metro would otherwise crawl them on every start.
const BUILD_TOOLS =
  /^(?:metro(?:-(?!runtime$).*)?|@react-native\/(?:community-cli-plugin|codegen|gradle-plugin|dev-middleware|metro-babel-transformer|babel-preset|metro-config)|@babel\/(?:core|preset-.+|plugin-.+|helper-.+|parser|generator|traverse|template|types)|hermes-compiler|typescript|vite|@types\/.+)$/;

// Farm's web runtime is never part of a React Native bundle.
const WEB_ONLY = new Set(["@farm.js/core", "@farm.js/cli", "@farm.js/mobile", "react-dom"]);

/** A package's real directory as Node resolves `name` from `from`, including pnpm's hoisted store. */
function packageDir(from: string, name: string): string | undefined {
  for (let dir = from; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, "node_modules", name);
    if (existsSync(path.join(candidate, "package.json"))) return realpathSync(candidate);
    if (path.dirname(dir) === dir) return undefined;
  }
}

function readManifest(dir: string): Record<string, Record<string, string> | undefined> {
  return JSON.parse(readFileSync(path.join(dir, "package.json"), "utf8"));
}

/**
 * Directories Metro must watch: the app, and the real directories of the packages a screen bundle
 * can reach (React Native, React, `@farm.js/native`, Babel's runtime helpers, and the app's own
 * dependencies), which pnpm keeps outside the app. Crawling only these, rather than a whole
 * workspace, keeps Metro's start fast.
 */
export function resolveWatchFolders(
  root: string,
  extra: ReadonlyArray<[from: string, name: string]> = [],
): string[] {
  const appRoot = realpathSync(root);
  const app = readManifest(appRoot);
  const queue: Array<[from: string, name: string]> = [
    ...Object.keys(app.dependencies ?? {}).map((name): [string, string] => [appRoot, name]),
    [appRoot, "react"],
    [appRoot, "react-native"],
    [appRoot, "@farm.js/native"],
  ];
  for (const [from, name] of extra) queue.push([realpathSync(from), name]);
  const seen = new Set<string>();
  while (queue.length > 0) {
    const [from, name] = queue.pop()!;
    if (BUILD_TOOLS.test(name) || WEB_ONLY.has(name)) continue;
    const dir = packageDir(from, name);
    if (!dir || seen.has(dir)) continue;
    seen.add(dir);
    const manifest = readManifest(dir);
    for (const field of ["dependencies", "peerDependencies", "optionalDependencies"] as const) {
      for (const dependency of Object.keys(manifest[field] ?? {})) queue.push([dir, dependency]);
    }
  }
  // pnpm links a package's dependencies next to it, so watch the `node_modules` that holds it.
  const marker = `${path.sep}node_modules${path.sep}`;
  const outside = [
    ...new Set(
      [...seen]
        .filter((dir) => dir !== appRoot && !dir.startsWith(`${appRoot}${path.sep}`))
        .map((dir) => {
          const at = dir.lastIndexOf(marker);
          return at === -1 ? dir : dir.slice(0, at + marker.length - 1);
        }),
    ),
  ].sort();
  // A package inside another watched package (a nested node_modules) is already crawled.
  const folders = outside.filter(
    (dir, index) =>
      !outside.slice(0, index).some((parent) => dir.startsWith(`${parent}${path.sep}`)),
  );
  return [appRoot, ...folders];
}

/** pnpm's hoisted store next to `dir`, the fallback for imports a package does not declare. */
function hoistedNodeModules(dir: string): string[] {
  const real = realpathSync(dir);
  const marker = `${path.sep}node_modules${path.sep}.pnpm${path.sep}`;
  const at = real.indexOf(marker);
  if (at === -1) return [];
  const hoisted = path.join(real.slice(0, at), "node_modules", ".pnpm", "node_modules");
  return existsSync(hoisted) ? [hoisted] : [];
}

// Generated native projects and other outputs hold many files Metro must never crawl.
const BLOCKED = [
  /[/\\]\.farm[/\\]output[/\\]mobile[/\\](?:android|ios|dist|www)[/\\].*/,
  /[/\\]\.farm[/\\](?:cache|types)[/\\].*/,
  /[/\\]\.gradle[/\\].*/,
  /[/\\]\.git[/\\].*/,
  /[/\\]\.output[/\\].*/,
];

const QUIET_REPORTER = {
  update(event: { type: string; error?: Error; level?: string; data?: unknown[] }) {
    if (event.type === "bundle_build_failed" || event.type === "bundling_error") {
      if (event.error) console.error(event.error.message);
    } else if (event.type === "client_log" && (event.level === "error" || event.level === "warn")) {
      console[event.level === "error" ? "error" : "warn"](...(event.data ?? []));
    }
  },
};

async function loadMetroConfig(
  root: string,
  toolchain: Toolchain,
  overrides: { port?: number; watchFolders: string[]; nodeModulesPaths: string[] },
): Promise<MetroConfig> {
  const defaults = toolchain.metroConfig.getDefaultConfig(root);
  // An app's metro.config.js, when it has one, wins over these defaults.
  const config = await toolchain.metro.loadConfig({ cwd: root, port: overrides.port }, defaults);
  const blockList = [config.resolver.blockList].flat().filter(Boolean);
  return {
    ...config,
    reporter: QUIET_REPORTER,
    // The hoisted store holds symlinks Metro follows into the watched package directories.
    watchFolders: [
      ...new Set([
        ...config.watchFolders,
        ...overrides.watchFolders,
        ...overrides.nodeModulesPaths,
      ]),
    ],
    resolver: {
      ...config.resolver,
      blockList: [...blockList, ...BLOCKED],
      nodeModulesPaths: [...config.resolver.nodeModulesPaths, ...overrides.nodeModulesPaths],
      resolveRequest: resolveSingletonsFromApp(root, config.resolver.resolveRequest),
    },
  };
}

/** Packages a bundle must hold exactly once: two Reacts or two React Natives break the runtime. */
const SINGLETONS = new Set(["react", "react-native"]);

type ResolveRequest = (context: any, moduleName: string, platform: string | null) => unknown;

/**
 * Resolves `react` and `react-native` (and their subpaths) from the app, whoever imports them.
 * A linked package, such as `@farm.js/native` in a workspace, otherwise gets its own copies
 * from its own `node_modules` and the bundle registers screens with a second React Native.
 */
export function resolveSingletonsFromApp(root: string, next?: ResolveRequest): ResolveRequest {
  const fromApp = path.join(root, "package.json");
  return (context, moduleName, platform) => {
    const name = moduleName.startsWith("@")
      ? moduleName.split("/").slice(0, 2).join("/")
      : moduleName.split("/")[0]!;
    const resolve = next ?? context.resolveRequest;
    if (SINGLETONS.has(name) && context.originModulePath !== fromApp) {
      return resolve({ ...context, originModulePath: fromApp }, moduleName, platform);
    }
    return resolve(context, moduleName, platform);
  };
}

export interface FarmNativeBuildOptions {
  root: string;
  /** `.farm/output/mobile/native`: the entry, the JS bundle, and the bytecode. */
  outDir: string;
  screens: readonly FarmNativeScreen[];
  basePath: string;
  locales?: readonly string[];
  platform?: "android" | "ios";
}

export interface FarmNativeBuild {
  reactNative: FarmReactNative;
  /** Hermes bytecode, bundled into the app as an asset. */
  bundle: string;
  /** Sizes in bytes. */
  jsBytes: number;
  bytecodeBytes: number;
  /** Wall time of the Metro bundle and the Hermes compile. */
  bundleMs: number;
  hermesMs: number;
}

async function writeEntry(options: FarmNativeBuildOptions): Promise<string> {
  const entryFile = path.join(options.outDir, "index.js");
  await mkdir(options.outDir, { recursive: true });
  const source = createFarmNativeEntry({ ...options, entryFile });
  const current = await readFile(entryFile, "utf8").catch(() => undefined);
  // Unchanged contents keep Metro's cache and Fast Refresh quiet.
  if (current !== source) await writeFile(entryFile, source);
  return entryFile;
}

/** `hermesc` from the `hermes-compiler` package react-native depends on. */
export function resolveHermesc(reactNative: FarmReactNative): string {
  const fromReactNative = createRequire(path.join(reactNative.dir, "package.json"));
  const dir = path.dirname(fromReactNative.resolve("hermes-compiler/package.json"));
  const bin =
    process.platform === "darwin"
      ? "osx-bin/hermesc"
      : process.platform === "win32"
        ? "win64-bin/hermesc.exe"
        : "linux64-bin/hermesc";
  const file = path.join(dir, "hermesc", bin);
  if (!existsSync(file)) throw nativeError(`hermesc is missing for ${process.platform}: ${file}`);
  return file;
}

function run(command: string, args: string[]): Promise<void> {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { stdio: ["ignore", "inherit", "inherit"] });
    child.once("error", reject);
    child.once("exit", (code) =>
      code === 0 ? resolve() : reject(new Error(`${path.basename(command)} exited with ${code}.`)),
    );
  });
}

/**
 * Where a build writes its bundle. Never `index.<platform>.js` next to the entry: Metro resolves
 * the dev entry `index` to `index.android.js` first, so `farm dev --mobile` would serve a stale
 * build instead of the screens' sources.
 */
export function farmNativeBundleFiles(
  outDir: string,
  platform: "android" | "ios",
): { js: string; bytecode: string } {
  const dir = path.join(outDir, "build");
  return { js: path.join(dir, `${platform}.js`), bytecode: path.join(dir, `${platform}.hbc`) };
}

/** Bundle every screen with Metro and compile the result to Hermes bytecode. */
export async function buildFarmNativeScreens(
  options: FarmNativeBuildOptions,
): Promise<FarmNativeBuild> {
  const reactNative = resolveFarmReactNative(options.root);
  const toolchain = loadToolchain(options.root, reactNative);
  const platform = options.platform ?? "android";
  const entryFile = await writeEntry(options);
  const config = await loadMetroConfig(options.root, toolchain, {
    watchFolders: resolveWatchFolders(options.root, toolchain.runtimeSeeds),
    nodeModulesPaths: hoistedNodeModules(reactNative.dir),
  });
  const { js, bytecode: bundle } = farmNativeBundleFiles(options.outDir, platform);
  await mkdir(path.dirname(js), { recursive: true });
  const started = performance.now();
  await toolchain.cliPlugin.unstable_buildBundleWithConfig(
    {
      entryFile,
      platform,
      dev: false,
      minify: true,
      bundleOutput: js,
      assetsDest: path.join(options.outDir, "res"),
      // The bundle's own console output; Metro's progress reporter is quiet.
      resetCache: false,
    },
    config,
  );
  const bundleMs = performance.now() - started;
  const hermesStarted = performance.now();
  await run(resolveHermesc(reactNative), ["-w", "-emit-binary", "-O", "-out", bundle, js]);
  const hermesMs = performance.now() - hermesStarted;
  return {
    reactNative,
    bundle,
    jsBytes: (await stat(js)).size,
    bytecodeBytes: (await stat(bundle)).size,
    bundleMs,
    hermesMs,
  };
}

export interface FarmNativeDevServerOptions extends FarmNativeBuildOptions {
  /** Metro's port; React Native's default 8081 when omitted. */
  port?: number;
  host?: string;
}

export interface FarmNativeDevServer {
  reactNative: FarmReactNative;
  port: number;
  /** The entry's path from the app root without `.js`: the shell's `jsMainModulePath`. */
  mainModule: string;
  /** Rewrites the entry for a new set of screens. */
  update(screens: readonly FarmNativeScreen[]): Promise<void>;
  close(): Promise<void>;
}

/**
 * Metro for `farm dev --mobile`: serves the entry to the debug app, with Fast Refresh over
 * Metro's HMR socket and React Native's DevTools middleware.
 */
export async function startFarmNativeDevServer(
  options: FarmNativeDevServerOptions,
): Promise<FarmNativeDevServer> {
  const reactNative = resolveFarmReactNative(options.root);
  const toolchain = loadToolchain(options.root, reactNative);
  const entryFile = await writeEntry(options);
  const port = options.port ?? 8081;
  const config = await loadMetroConfig(options.root, toolchain, {
    port,
    watchFolders: resolveWatchFolders(options.root, toolchain.runtimeSeeds),
    nodeModulesPaths: hoistedNodeModules(reactNative.dir),
  });
  const serverBaseUrl = `http://localhost:${port}`;
  const { middleware, websocketEndpoints } = toolchain.devMiddleware.createDevMiddleware({
    serverBaseUrl,
    logger: undefined,
  });
  // The app checks /status before it asks for the bundle (React Native's PackagerStatusCheck).
  const status = (req: any, res: any, next: () => void) => {
    if (req.url !== "/status") return next();
    res.setHeader("X-React-Native-Project-Root", config.projectRoot);
    res.end("packager-status:running");
  };
  const { httpServer } = await toolchain.metro.runServer(config, {
    host: options.host,
    unstable_extraMiddleware: [status, middleware],
    websocketEndpoints,
  });
  const mainModule = path
    .relative(options.root, entryFile)
    .split(path.sep)
    .join("/")
    .replace(/\.js$/, "");
  return {
    reactNative,
    port,
    mainModule,
    async update(screens) {
      await writeEntry({ ...options, screens });
    },
    close: closeWithConnections(httpServer),
  };
}

/**
 * A close for a server whose clients keep sockets open: the debug app holds Metro's HMR and
 * DevTools websockets for as long as it runs, so `server.close()` alone never finishes and
 * `farm dev --mobile` would hang on Ctrl+C. Tracks every socket and destroys them on close.
 */
export function closeWithConnections(server: import("node:http").Server): () => Promise<void> {
  const sockets = new Set<import("node:net").Socket>();
  server.on("connection", (socket) => {
    sockets.add(socket);
    socket.once("close", () => sockets.delete(socket));
  });
  return () =>
    new Promise<void>((resolve) => {
      server.close(() => resolve());
      for (const socket of sockets) socket.destroy();
    });
}
