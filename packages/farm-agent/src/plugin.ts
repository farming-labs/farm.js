import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { definePlugin } from "@farm.js/core/plugin";
import type { AgentUnitConfig } from "agent-unit";
import type { DevHandler } from "agent-unit/build";
import type { agentUnit } from "agent-unit/nitro";

type Nitro = Parameters<NonNullable<ReturnType<typeof agentUnit>["setup"]>>[0];

// agent-unit's build and dev servers load only in Farm's own process. Farm bundles farm.config into
// the production server, and a bundler follows literal imports, so these must not be literal.
const loadBuildOnly = <T>(specifier: string): Promise<T> => import(/* @vite-ignore */ specifier);

/** Set by the built server's agent module (see SERVER_MODULE): agent-unit's engine. */
const AGENT_SERVER = Symbol.for("farm.agent.server");
type AgentServer = { handle(request: Request): Promise<Response> };
type ServerHolder = { [AGENT_SERVER]?: AgentServer };

// Every method agent-unit answers: the run API, MCP and the internal continue and sweep endpoints.
const METHODS = ["get", "post", "delete"] as const;

export function isUnder(pathname: string, basePath: string): boolean {
  return basePath === "/" || pathname === basePath || pathname.startsWith(`${basePath}/`);
}

// The built server's agent module, next to agent-unit's runtime. It hands the engine to the routes
// below, and as Nitro middleware on the agent paths it passes on the host's waitUntil, which only
// hosts that keep work alive after the response have, as agent-unit's own entry does.
const SERVER_MODULE = `// Generated by @farm.js/agent. Do not edit.
import { AsyncLocalStorage } from "node:async_hooks";
import { getUnit } from "./runtime.mjs";

const hostWaitUntil = new AsyncLocalStorage();

globalThis[Symbol.for("farm.agent.server")] = {
  handle(request) {
    const waitUntil = hostWaitUntil.getStore();
    return getUnit().handler(request, waitUntil ? { waitUntil } : {});
  },
};

export default function farmAgentHost(event, next) {
  const req = event.req;
  return typeof req.waitUntil === "function"
    ? hostWaitUntil.run((promise) => req.waitUntil(promise), next)
    : next();
}
`;

// Nitro's Vercel preset runs scheduled tasks from a public cron route that checks CRON_SECRET only
// when it is set. As Nitro middleware on that route, this module rejects every call without the
// secret, the way Farm's own cron routes do.
const CRON_GUARD_MODULE = `// Generated by @farm.js/agent. Do not edit.
import { isCronRequestAuthorized } from "@farm.js/core/cron";

export default function farmAgentCronGuard(event, next) {
  if (isCronRequestAuthorized(event.req)) return next();
  return Response.json({ error: "Unauthorized cron request." }, { status: 401 });
}
`;

/** Guards Nitro's Vercel cron route when agent-unit has scheduled the sweep or the app's tasks. */
function guardVercelCron(nitro: Nitro, dir: string): void {
  const preset = String(nitro.options.preset ?? "");
  if (!preset.startsWith("vercel")) return;
  if (!nitro.options.experimental?.tasks) return;
  if (Object.keys(nitro.options.scheduledTasks ?? {}).length === 0) return;

  const route = nitro.options.vercel?.cronHandlerRoute || "/_vercel/cron";
  const guard = path.posix.join(dir, "farm-cron-guard.mjs");
  writeFileSync(guard, CRON_GUARD_MODULE);
  nitro.options.handlers.unshift(
    { route, handler: guard, middleware: true, lazy: false },
    { route: `${route}/**`, handler: guard, middleware: true, lazy: false },
  );
  if (!process.env.CRON_SECRET) {
    nitro.logger.warn(
      `@farm.js/agent: Vercel Cron runs the agent sweep and tasks at ${route}, which rejects every call without CRON_SECRET. Set CRON_SECRET in the Vercel project's environment variables, or the scheduled runs answer 401.`,
    );
  }
}

/**
 * Serves the agents in `farm dev` and builds them into the production server, as API routes under
 * `basePath`: Farm's middleware, plugin guards and integration guards run for them as for any route.
 */
export function createAgentPlugin(config: AgentUnitConfig & { basePath: string }) {
  const { basePath } = config;
  // Set by `configure`, in Farm's process: farm.config also evaluates inside the server, where a
  // Worker has no working directory.
  let root: string | undefined;
  let agentsDir = config.agentsDir ?? "agents";
  let isDev = false;
  let devHandler: Promise<DevHandler> | undefined;

  const buildConfig = (): AgentUnitConfig => ({ ...config, agentsDir });
  const startDev = () =>
    (devHandler ??= loadBuildOnly<typeof import("agent-unit/build")>("agent-unit/build").then(
      ({ createDevHandler }) =>
        createDevHandler({ root: root ?? process.cwd(), config: buildConfig() }),
    ));
  const closeDev = async () => {
    const pending = devHandler;
    devHandler = undefined;
    await (await pending?.catch(() => undefined))?.close();
  };

  const handle = async (request: Request): Promise<Response> => {
    // A dev server runs the agents from source, kept across Vite restarts.
    if (isDev) return (await startDev()).fetch(request);
    const server = (globalThis as ServerHolder)[AGENT_SERVER];
    if (!server) {
      throw new Error(
        "@farm.js/agent: this server was built without the agents. Build it with `farm build`, which adds them.",
      );
    }
    return server.handle(request);
  };

  return definePlugin({
    name: "farm:agent",
    configure(farmConfig, context) {
      root = path.resolve(farmConfig.root ?? process.cwd());
      agentsDir = config.agentsDir ?? path.posix.join(farmConfig.srcDir ?? "src", "agents");
      isDev = context.isDev;
    },
    // Ordinary API routes, so a request passes Farm's middleware, runtime.before and integration
    // guards before it reaches the agents, in development and in every production target.
    routes: ({ route }) =>
      METHODS.flatMap((method) =>
        [basePath, `${basePath}/[...path]`].map((pattern) =>
          route[method](pattern, { handler: (request) => handle(request) }),
        ),
      ),
    router: {
      // agent-unit answers every path under basePath, so an app route there would never be reached.
      discovered(route) {
        if (route.kind !== "api" || !route.filePath || !isUnder(route.path, basePath)) return;
        throw new Error(
          `@farm.js/agent: ${route.filePath} is served at ${route.path}, which the agent API owns (basePath "${basePath}"). Move the route, or set another basePath.`,
        );
      },
    },
    build: {
      // agent-unit builds the agents into Farm's Nitro output for its preset: their framework
      // adapters, storage, the sweep and `tasks` as scheduled tasks. Its own handler for basePath
      // would answer before Farm's, so Farm's routes serve the API instead.
      async configure(nitroConfig) {
        const { agentUnit } =
          await loadBuildOnly<typeof import("agent-unit/nitro")>("agent-unit/nitro");
        const unit = agentUnit({
          root: root ?? process.cwd(),
          basePath,
          config: buildConfig(),
          // The module agent-unit's engine reads its config from in the built server.
          configFile: fileURLToPath(new URL("./config.js", import.meta.url)),
        });
        const module: typeof unit = {
          name: unit.name,
          async setup(nitro) {
            const before = nitro.options.handlers.length;
            await unit.setup!(nitro);
            const added = nitro.options.handlers.splice(before);
            const entry = added.find((handler) => handler.handler.endsWith("entry.mjs"))?.handler;
            if (!entry) {
              throw new Error(
                "@farm.js/agent: agent-unit's Nitro module did not mount its handler. Install the agent-unit version @farm.js/agent supports.",
              );
            }
            nitro.options.handlers.push(...added.filter((handler) => handler.handler !== entry));
            // Nitro writes handler paths into generated imports, so keep them in forward-slash
            // form; a Windows `D:\…` path would lose its backslashes there.
            const server = path.posix.join(
              path.posix.dirname(entry.replaceAll("\\", "/")),
              "farm-server.mjs",
            );
            writeFileSync(server, SERVER_MODULE);
            guardVercelCron(nitro, path.posix.dirname(server));
            nitro.options.handlers.push(
              { route: basePath, handler: server, middleware: true, lazy: false },
              { route: `${basePath}/**`, handler: server, middleware: true, lazy: false },
            );
          },
        };
        return { ...nitroConfig, modules: [...(nitroConfig.modules ?? []), module] };
      },
    },
    dev: {
      server(_viteServer, { lifecycle }) {
        void startDev().catch(() => {});
        lifecycle.onShutdown(closeDev);
      },
    },
    runtime: {
      close: closeDev,
    },
  });
}
