import { readFile } from "node:fs/promises";
import path from "node:path";
import type { MobileGeneratedFile, MobileShellContext } from "@farm.js/core/mobile";
import type { AndroidNativeModule } from "./autolinking.js";

/**
 * The app's own TurboModules on Android (RFC 0004, 7.5): the Codegen specs and Kotlin classes in
 * `src/native/`, copied into a local library that links like a community module. The library is
 * one more `autolinking.json` entry, so React Native's Gradle plugin runs Codegen for its specs,
 * builds its JNI library into `libappmodules.so`, and adds its package to `PackageList`.
 */

/** The library's directory in the generated project, and its `autolinking.json` name. */
export const APP_MODULES_DIR = "farm-app-modules";
/** Codegen's library name: `react_codegen_FarmAppSpec` and `FarmAppSpec_ModuleProvider`. */
export const APP_MODULES_LIBRARY = "FarmAppSpec";
/** The Java package Codegen writes the specs to, such as `dev.farmjs.mobile.specs.NativeDeviceSpec`. */
export const APP_MODULES_SPEC_PACKAGE = "dev.farmjs.mobile.specs";
/** The generated `ReactPackage` that creates the app's modules. */
const PACKAGE_NAMESPACE = "dev.farmjs.mobile.modules";
const PACKAGE_CLASS = "FarmAppModulesPackage";

const GENERATED =
  "Generated by @farm.js/mobile/android on every farm dev|build --mobile from src/native. Do not edit.";
/** XML comments cannot contain "--", so the manifest says it without the flag. */
const XML_GENERATED =
  "Generated by @farm.js/mobile/android on every mobile dev or build from src/native. Do not edit.";

/** An import of the shell's own package, which the app modules' library cannot compile against. */
const SHELL_IMPORT = /^\s*import\s+(dev\.farmjs\.mobile\.shell(?:\.[\w*]+)*)/m;

function mobileError(message: string): Error {
  return Object.assign(new Error(message), { name: "FarmMobileError" });
}

function slash(file: string): string {
  return file.split(path.sep).join("/");
}

/** A Kotlin class whose superclass is a Codegen spec, such as `NativeDeviceSpec(reactContext)`. */
const MODULE_CLASS = /\bclass\s+(\w+)\s*(?:\([^)]*\))?\s*:\s*(?:[\w.]+\.)?(Native\w+Spec)\s*\(/g;
const KOTLIN_PACKAGE = /^\s*package\s+([\w.]+)/m;

interface KotlinFile {
  file: string;
  source: string;
  javaPackage: string;
}

interface AppModuleClass {
  /** The name the spec registers, such as `"Device"`. */
  name: string;
  /** Fully qualified Kotlin class, such as `com.example.DeviceModule`. */
  className: string;
}

export interface AndroidAppModules {
  module: AndroidNativeModule;
  files: MobileGeneratedFile[];
}

function createPackageClass(classes: AppModuleClass[]): string {
  const cases = classes
    .map((entry) => `            ${JSON.stringify(entry.name)} -> ${entry.className}(reactContext)`)
    .join("\n");
  const infos = classes
    .map(
      (entry) =>
        `            ${JSON.stringify(entry.name)} to ReactModuleInfo(${JSON.stringify(entry.name)}, ` +
        `${JSON.stringify(entry.className)}, false, false, false, true),`,
    )
    .join("\n");
  return `// ${GENERATED}
package ${PACKAGE_NAMESPACE}

import com.facebook.react.BaseReactPackage
import com.facebook.react.bridge.NativeModule
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.module.model.ReactModuleInfo
import com.facebook.react.module.model.ReactModuleInfoProvider

/** The app's own TurboModules from src/native, autolinked like a community module. */
class ${PACKAGE_CLASS} : BaseReactPackage() {
    override fun getModule(name: String, reactContext: ReactApplicationContext): NativeModule? =
        when (name) {
${cases}
            else -> null
        }

    override fun getReactModuleInfoProvider(): ReactModuleInfoProvider = ReactModuleInfoProvider {
        mapOf(
${infos}
        )
    }
}
`;
}

function createLibraryBuildGradle(reactNativeVersion: string): string {
  return `// ${GENERATED}
plugins {
    id("com.android.library")
    id("org.jetbrains.kotlin.android")
    // Codegen for the specs in ../specs (codegenConfig in ../package.json).
    id("com.facebook.react")
}

android {
    namespace = ${JSON.stringify(PACKAGE_NAMESPACE)}
    compileSdk = (rootProject.extra["compileSdkVersion"] as Number).toInt()

    defaultConfig {
        minSdk = (rootProject.extra["minSdkVersion"] as Number).toInt()
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }
}

dependencies {
    implementation("com.facebook.react:react-android:${reactNativeVersion}")
}
`;
}

function createLibraryPackageJson(): string {
  const pkg = {
    name: APP_MODULES_DIR,
    private: true,
    description: GENERATED,
    codegenConfig: {
      name: APP_MODULES_LIBRARY,
      type: "modules",
      jsSrcsDir: "specs",
      android: { javaPackageName: APP_MODULES_SPEC_PACKAGE },
    },
  };
  return `${JSON.stringify(pkg, null, 2)}\n`;
}

/**
 * The library for the app's own modules, or undefined when the app has no specs in
 * `src/native/` or no React Native screens. Every spec needs one Kotlin class that extends its
 * Codegen base class; a missing or duplicate class throws, naming the spec and the fix.
 */
export async function resolveAndroidAppModules(
  context: MobileShellContext,
): Promise<AndroidAppModules | undefined> {
  const app = context.appModules;
  if (!context.native || !app || app.specs.length === 0) return undefined;
  const shown = (file: string) => slash(path.relative(context.root, file));

  const kotlin: KotlinFile[] = [];
  for (const file of app.android) {
    const source = await readFile(file, "utf8");
    const javaPackage = KOTLIN_PACKAGE.exec(source)?.[1];
    if (!javaPackage) {
      throw mobileError(
        `${shown(file)} has no package declaration. Start it with one, such as ` +
          `"package ${context.mobile.id}.modules", so Farm can register its classes.`,
      );
    }
    const shell = SHELL_IMPORT.exec(source);
    if (shell) {
      throw mobileError(
        `${shown(file)} imports ${shell[1]}, a class of Farm's Android shell. App modules build as ` +
          `their own Gradle module (${APP_MODULES_DIR}), which cannot see the shell. Remove the ` +
          'import: write files for web screens into File(context.cacheDir, "farm-files") by name, ' +
          "and use React Native's APIs for the rest.",
      );
    }
    kotlin.push({ file, source, javaPackage });
  }

  const classes: AppModuleClass[] = [];
  for (const spec of app.specs) {
    const base = `${path.basename(spec.file).replace(/\.\w+$/, "")}Spec`;
    const found: Array<{ file: KotlinFile; className: string }> = [];
    for (const file of kotlin) {
      for (const match of file.source.matchAll(MODULE_CLASS)) {
        if (match[2] === base) found.push({ file, className: `${file.javaPackage}.${match[1]}` });
      }
    }
    if (found.length === 0) {
      throw mobileError(
        `${shown(spec.file)} registers the native module "${spec.name}", but no Kotlin class in ` +
          `${shown(app.dir)} extends ${base}. Add one, such as ${shown(app.dir)}/${spec.name}Module.kt ` +
          `with "class ${spec.name}Module(reactContext: ReactApplicationContext) : ${base}(reactContext)" ` +
          `and "import ${APP_MODULES_SPEC_PACKAGE}.${base}".`,
      );
    }
    if (found.length > 1) {
      throw mobileError(
        `${found.map((entry) => entry.className).join(" and ")} both extend ${base}. Keep one ` +
          `class for the native module "${spec.name}".`,
      );
    }
    classes.push({ name: spec.name, className: found[0]!.className });
  }

  const root = `${slash(context.projectDir)}/${APP_MODULES_DIR}`;
  const sourceDir = `${root}/android`;
  const javaDir = `${APP_MODULES_DIR}/android/src/main/java`;
  const files: MobileGeneratedFile[] = [
    { path: `${APP_MODULES_DIR}/package.json`, contents: createLibraryPackageJson() },
    ...(await Promise.all(
      app.specs.map(async (spec) => ({
        path: `${APP_MODULES_DIR}/specs/${path.basename(spec.file)}`,
        contents: await readFile(spec.file, "utf8"),
      })),
    )),
    {
      path: `${APP_MODULES_DIR}/android/build.gradle.kts`,
      contents: createLibraryBuildGradle(context.native.reactNativeVersion),
    },
    {
      path: `${APP_MODULES_DIR}/android/src/main/AndroidManifest.xml`,
      contents: `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${XML_GENERATED} -->\n<manifest />\n`,
    },
    {
      path: `${javaDir}/${PACKAGE_NAMESPACE.replace(/\./g, "/")}/${PACKAGE_CLASS}.kt`,
      contents: createPackageClass(classes),
    },
    ...kotlin.map((entry) => ({
      path: `${javaDir}/${entry.javaPackage.replace(/\./g, "/")}/${path.basename(entry.file)}`,
      contents: entry.source,
    })),
  ];
  return {
    module: {
      name: APP_MODULES_DIR,
      root,
      android: {
        sourceDir,
        packageImportPath: `import ${PACKAGE_NAMESPACE}.${PACKAGE_CLASS};`,
        packageInstance: `new ${PACKAGE_CLASS}()`,
        buildTypes: [],
        libraryName: APP_MODULES_LIBRARY,
        componentDescriptors: [],
        cmakeListsPath: `${sourceDir}/build/generated/source/codegen/jni/CMakeLists.txt`,
        cxxModuleCMakeListsModuleName: null,
        cxxModuleCMakeListsPath: null,
        cxxModuleHeaderName: null,
        dependencyConfiguration: null,
        isPureCxxDependency: false,
      },
    },
    files,
  };
}
