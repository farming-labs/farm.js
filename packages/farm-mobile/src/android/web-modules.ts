function mobileError(message: string): Error {
  return Object.assign(new Error(message), { name: "FarmMobileError" });
}

/** A Kotlin string literal. JSON's escapes are Kotlin's, except `$`, which starts a template. */
function kotlinString(value: string): string {
  return JSON.stringify(value).replace(/\$/g, "\\$");
}

/** The runtime description of a spec type, which `convert` checks JSON against. */
function kotlinType(type: FarmNativeType): string {
  const nullable = type.nullable ? ", nullable = true" : "";
  switch (type.type) {
    case "string":
    case "boolean":
    case "map":
      return `FarmWebType(${kotlinString(type.type)}${nullable})`;
    case "number":
      return `FarmWebType("number"${nullable}${type.integer ? ", integer = true" : ""})`;
    case "literal": {
      const values = type.values
        .map((value) => (typeof value === "string" ? kotlinString(value) : `${Number(value)}`))
        .map((value) => (/^-?\d+$/.test(value) ? `${value}.0` : value))
        .join(", ");
      return `FarmWebType("literal"${nullable}, values = listOf(${values}))`;
    }
    case "array":
      return type.element
        ? `FarmWebType("array"${nullable}, element = ${kotlinType(type.element)})`
        : `FarmWebType("array"${nullable})`;
    case "object":
      return `FarmWebType("object"${nullable}, properties = listOf(${type.properties
        .map(
          (property) =>
            `FarmWebParam(${kotlinString(property.name)}, ${property.optional}, ${kotlinType(property.type)})`,
        )
        .join(", ")}))`;
    case "void":
    case "unknown":
      throw new Error(`A ${type.type} type is not a parameter type.`);
  }
}

/** The Kotlin type Codegen's Java spec method takes for a parameter, such as `Double?`. */
function kotlinParamType(type: FarmNativeType, optional: boolean): string {
  let name: string;
  switch (type.type) {
    case "string":
      name = "String";
      break;
    case "number":
      name = "Double";
      break;
    case "boolean":
      name = "Boolean";
      break;
    case "literal":
      name = type.values.every((value) => typeof value === "string") ? "String" : "Double";
      break;
    case "object":
    case "map":
      name = "ReadableMap";
      break;
    case "array":
      name = "ReadableArray";
      break;
    default:
      throw new Error(`A ${type.type} type is not a parameter type.`);
  }
  return optional || type.nullable ? `${name}?` : name;
}

function createMethod(method: FarmNativeMethod, constant: string, specClass: string): string {
  const args = method.params
    .map((param, index) => `a[${index}] as ${kotlinParamType(param.type, param.optional)}, `)
    .join("");
  const uses = method.params.length > 0 ? "a" : "_";
  return (
    `            ${kotlinString(method.name)} -> checkArgs(method, args, ${constant}).let { ${uses} ->\n` +
    `                { module: ${specClass}, promise: Promise -> module.${method.name}(${args}promise) }\n` +
    "            }"
  );
}

function constantName(method: string): string {
  return method.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
}

function createModule(name: string, specClass: string, methods: FarmNativeMethod[]): string {
  const objectName = `${name}WebModule`;
  const cases = methods.map((method) => createMethod(method, constantName(method.name), specClass));
  const params = methods.map(
    (method) =>
      `    private val ${constantName(method.name)} = listOf<FarmWebParam>(${method.params
        .map(
          (param) =>
            `FarmWebParam(${kotlinString(param.name)}, ${param.optional}, ${kotlinType(param.type)})`,
        )
        .join(", ")})`,
  );
  return `/** ${name}: the Promise methods of its spec, as web screens send them. */
private object ${objectName} : FarmWebModule<${specClass}>(${kotlinString(name)}, ${specClass}::class.java) {
    override fun bind(method: String, args: JSONArray): (${specClass}, Promise) -> Unit =
        when (method) {
${cases.join("\n")}
            else -> throw unknownMethod(method)
        }

${params.join("\n")}
}`;
}

const RUNTIME = `/**
 * One app module for web screens. [bind] checks a call's arguments against the spec on the main
 * thread, before anything runs; the method then runs on the module instance React Native screens
 * use, on React Native's native-modules thread, as a call from a native screen would.
 */
private abstract class FarmWebModule<Spec : NativeModule>(
    override val name: String,
    private val spec: Class<Spec>,
) : FarmPlugin {
    /** The call to run, or a [FarmCallException] when [method] or [args] do not match the spec. */
    abstract fun bind(method: String, args: JSONArray): (Spec, Promise) -> Unit

    override fun callAsync(method: String, args: Any?, webView: WebView, result: FarmCallResult) {
        val list = args as? JSONArray
            ?: throw invalid("$name.$method takes its arguments as an array, such as [200].")
        val bound = bind(method, list)
        // The shared React Native runtime, created as a native screen creates it; null once it failed.
        val host = (FarmNativeScreens.engine as? ReactNativeEngine)?.host()
            ?: throw FarmCallException("native_unavailable", "React Native is not running in this app, so $name is unavailable.")
        starter.execute {
            try {
                // A web screen can call before the runtime warmed up: start it as a native screen would.
                val context = host.currentReactContext ?: host.start().let { started ->
                    started.waitForCompletion(START_TIMEOUT_SECONDS, TimeUnit.SECONDS)
                    host.currentReactContext
                }
                if (context == null) {
                    result.reject("native_unavailable", "React Native did not start, so $name is unavailable.")
                    return@execute
                }
                context.runOnNativeModulesQueueThread {
                    try {
                        val module = context.getNativeModule(name)
                        if (module == null || !spec.isInstance(module)) {
                            result.reject("native_unavailable", "The app has no native module \\"$name\\".")
                        } else {
                            bound(spec.cast(module)!!, FarmWebPromise(result))
                        }
                    } catch (error: Throwable) {
                        result.reject("native_error", error.message ?: error.toString())
                    }
                }
            } catch (error: Throwable) {
                result.reject("native_unavailable", "React Native could not run $name: \${error.message ?: error}")
            }
        }
    }

    protected fun unknownMethod(method: String) = FarmCallException(
        "unknown_method",
        "$name has no method \\"$method\\" that returns a Promise, and web screens call only those.",
    )

    /** The arguments, converted to the types Codegen's Java spec takes. */
    protected fun checkArgs(method: String, args: JSONArray, params: List<FarmWebParam>): Array<Any?> {
        if (args.length() > params.size) {
            throw invalid("$name.$method takes \${params.size} argument\${if (params.size == 1) "" else "s"}, got \${args.length()}.")
        }
        return Array(params.size) { index ->
            val param = params[index]
            val at = "$name.$method argument \${index + 1} (\${param.name})"
            if (index >= args.length()) {
                if (!param.optional) throw invalid("$at is required.")
                null
            } else {
                convert(args.opt(index), param.type, at, param.optional)
            }
        }
    }

    private companion object {
        /** One thread waits for React Native to start, so calls keep their order. */
        val starter = Executors.newSingleThreadExecutor { task -> Thread(task, "farm-web-modules") }
        const val START_TIMEOUT_SECONDS = 30L
    }
}

/** A value a spec declares: string, number, boolean, literal, object, map, or array. */
private class FarmWebType(
    val kind: String,
    val nullable: Boolean = false,
    val integer: Boolean = false,
    val values: List<Any> = emptyList(),
    val element: FarmWebType? = null,
    val properties: List<FarmWebParam> = emptyList(),
)

private class FarmWebParam(val name: String, val optional: Boolean, val type: FarmWebType)

private fun invalid(message: String) = FarmCallException("invalid_args", message)

private fun shown(value: Any?): String = if (value == null || value == JSONObject.NULL) "null" else JSONObject.wrap(value)?.let {
    if (it is String) JSONObject.quote(it) else it.toString()
} ?: value.toString()

private fun expected(type: FarmWebType): String = when (type.kind) {
    "string" -> "a string"
    "number" -> if (type.integer) "a whole number" else "a number"
    "boolean" -> "true or false"
    "literal" -> "one of " + type.values.joinToString(", ") { if (it is String) JSONObject.quote(it) else it.toString() }
    "array" -> "an array"
    else -> "an object"
} + if (type.nullable) " or null" else ""

/** [value] from JSON as the Java type Codegen's spec takes, or [FarmCallException] naming [at]. */
private fun convert(value: Any?, type: FarmWebType, at: String, optional: Boolean = false): Any? {
    if (value == null || value == JSONObject.NULL) {
        if (type.nullable || optional) return null
        throw invalid("$at must be \${expected(type)}, got null.")
    }
    val mismatch = { invalid("$at must be \${expected(type)}, got \${shown(value)}.") }
    return when (type.kind) {
        "string" -> value as? String ?: throw mismatch()
        "boolean" -> value as? Boolean ?: throw mismatch()
        "number" -> {
            val number = (value as? Number)?.toDouble()?.takeIf { it.isFinite() } ?: throw mismatch()
            if (type.integer && (number != Math.rint(number) || number < Int.MIN_VALUE || number > Int.MAX_VALUE)) {
                throw mismatch()
            }
            number
        }
        "literal" -> {
            val literal: Any = if (value is Number) value.toDouble() else value
            if (literal in type.values) literal else throw mismatch()
        }
        "map" -> toReadable(value as? JSONObject ?: throw mismatch())
        "object" -> {
            val json = value as? JSONObject ?: throw mismatch()
            val declared = type.properties.associateBy { it.name }
            for (key in json.keys()) {
                if (key !in declared) throw invalid("$at has the property \\"$key\\", which the spec does not declare.")
            }
            val map = HashMap<String, Any?>()
            for (property in type.properties) {
                val where = "$at.\${property.name}"
                if (!json.has(property.name)) {
                    if (!property.optional) throw invalid("$where is required.")
                    continue
                }
                map[property.name] = convert(json.opt(property.name), property.type, where, property.optional)
            }
            JavaOnlyMap.from(map)
        }
        "array" -> {
            val json = value as? JSONArray ?: throw mismatch()
            val element = type.element
            JavaOnlyArray.from(
                List(json.length()) { index ->
                    if (element == null) toReadable(json.opt(index)) else convert(json.opt(index), element, "$at[$index]")
                },
            )
        }
        else -> throw mismatch()
    }
}

/** Any JSON as React Native's map and array types, numbers as doubles. */
private fun toReadable(value: Any?): Any? = when (value) {
    null, JSONObject.NULL -> null
    is JSONObject -> JavaOnlyMap.from(value.keys().asSequence().associateWith { toReadable(value.opt(it)) })
    is JSONArray -> JavaOnlyArray.from(List(value.length()) { toReadable(value.opt(it)) })
    is Number -> value.toDouble()
    else -> value
}

/** A module's result as JSON for the bridge. */
private fun toJson(value: Any?): Any? = when (value) {
    null, Unit -> null
    is ReadableMap -> JSONObject(value.toHashMap() as Map<*, *>)
    is ReadableArray -> JSONArray(value.toArrayList())
    is Map<*, *> -> JSONObject(value)
    is Collection<*> -> JSONArray(value)
    else -> value
}

/** React Native's Promise, answering the bridge: resolve as JSON, reject as { code, message }. */
private class FarmWebPromise(private val result: FarmCallResult) : Promise {
    override fun resolve(value: Any?) {
        val json = try {
            toJson(value)
        } catch (error: Exception) {
            return result.reject("native_error", "The result is not JSON: \${error.message}")
        }
        result.resolve(json)
    }

    override fun reject(code: String?, message: String?) = fail(code, message, null)

    override fun reject(code: String?, throwable: Throwable?) = fail(code, null, throwable)

    override fun reject(code: String?, message: String?, throwable: Throwable?) = fail(code, message, throwable)

    override fun reject(throwable: Throwable) = fail(null, null, throwable)

    override fun reject(throwable: Throwable, userInfo: WritableMap) = fail(null, null, throwable)

    override fun reject(code: String?, userInfo: WritableMap) = fail(code, null, null)

    override fun reject(code: String?, throwable: Throwable?, userInfo: WritableMap) = fail(code, null, throwable)

    override fun reject(code: String?, message: String?, userInfo: WritableMap) = fail(code, message, null)

    override fun reject(code: String?, message: String?, throwable: Throwable?, userInfo: WritableMap?) =
        fail(code, message, throwable)

    @Deprecated("Prefer passing a module-specific error code to JS.")
    override fun reject(message: String) = fail(null, message, null)

    private fun fail(code: String?, message: String?, throwable: Throwable?) {
        // React Native's own code for a rejection without one.
        result.reject(code ?: "EUNSPECIFIED", message ?: throwable?.message ?: "Native call failed.")
    }
}`;

/** The dispatcher file for the opted-in modules. */
function createWebModulesFile(
  modules: Array<{ name: string; specClass: string; methods: FarmNativeMethod[] }>,
): string {
  const imports = [
    "android.webkit.WebView",
    "com.facebook.react.bridge.JavaOnlyArray",
    "com.facebook.react.bridge.JavaOnlyMap",
    "com.facebook.react.bridge.NativeModule",
    "com.facebook.react.bridge.Promise",
    "com.facebook.react.bridge.ReadableArray",
    "com.facebook.react.bridge.ReadableMap",
    "com.facebook.react.bridge.WritableMap",
    ...modules.map((module) => `${APP_MODULES_SPEC_PACKAGE}.${module.specClass}`),
    "java.util.concurrent.Executors",
    "java.util.concurrent.TimeUnit",
    "org.json.JSONArray",
    "org.json.JSONObject",
  ];
  return `// ${GENERATED}
package dev.farmjs.mobile.shell

${imports.map((name) => `import ${name}`).join("\n")}

/**
 * The FarmPlugin of each app module with mobile.modules.<name>.web (RFC 0004, 7.5). The bridge
 * dispatches \`call\` messages from web screens only to these modules, and only to the Promise
 * methods of their Codegen specs.
 */
internal fun farmWebModules(): Map<String, FarmPlugin> = listOf<FarmPlugin>(
${modules.map((module) => `    ${module.name}WebModule,`).join("\n")}
).associateBy { it.name }

${modules.map((module) => createModule(module.name, module.specClass, module.methods)).join("\n\n")}

${RUNTIME}
`;
}

function patch(
  file: MobileGeneratedFile | undefined,
  from: string,
  to: string,
): MobileGeneratedFile {
  const source = String(file?.contents ?? "");
  if (!file || !source.includes(from)) {
    throw new Error(`${file?.path ?? "A shell file"} no longer contains "${from.trim()}".`);
  }
  return { ...file, contents: source.replace(from, to) };
}

/**
 * The files that change when app modules opt in for web screens: the dispatcher, `MainActivity`
 * registering it, and the engine's `host()` it starts React Native with. Empty when none opts in.
 * Throws when a module opts in but the Android app has no React Native, which runs the module.
 */
export function createAndroidWebModules(
  context: MobileShellContext,
  files: ReadonlyMap<string, MobileGeneratedFile>,
): MobileGeneratedFile[] {
  const specs = (context.appModules?.specs ?? []).filter((spec) => spec.web);
  if (specs.length === 0) return [];
  if (!context.native) {
    const names = specs.map((spec) => `mobile.modules.${spec.name}.web`).join(", ");
    throw mobileError(
      `${names} needs React Native in the Android app to run the module, and Farm adds it only ` +
        "when a route has a native screen (page.native.tsx). Add one, or remove web.",
    );
  }
  const modules = specs.map((spec) => ({
    name: spec.name,
    specClass: `${path.basename(spec.file).replace(/\.\w+$/, "")}Spec`,
    methods: spec.web!.methods,
  }));
  return [
    { path: WEB_MODULES_FILE, contents: createWebModulesFile(modules) },
    patch(files.get(MAIN_ACTIVITY), PLUGINS_FROM, PLUGINS_TO),
    patch(files.get(NATIVE_ENGINE), HOST_FROM, HOST_TO),
  ];
}
