/**
 * Web screens' calls to app native modules on Android (RFC 0004, 7.5). For each module with
 * `mobile.modules.<name>.web`, core reads the Promise methods of its Codegen spec; this file turns
 * them into one `FarmPlugin` that checks a call's JSON arguments against those types, then runs the
 * method on the module instance React Native screens use, through a `Promise` that answers the
 * bridge. Nothing is generated when no module opts in.
 */

