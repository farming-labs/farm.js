/** SF Symbols for the tab icon names the Android shell also ships. */
const TAB_SYMBOLS: Record<string, string> = {
  home: "house",
  notes: "note.text",
  person: "person",
  search: "magnifyingglass",
  settings: "gearshape",
  gear: "gearshape",
};

/**
 * The SF Symbol for a `mobile.tabs[].icon`: the shared names (`notes`, `ic_settings`, `gear`) map
 * to their symbols, anything else is used as a symbol name. The shell falls back to a generic
 * symbol when the system has no symbol by that name.
 */
export function resolveTabSymbol(icon: string): string {
  const name = icon.replace(/^ic_/i, "");
  return TAB_SYMBOLS[name.toLowerCase()] ?? name;
}

/** A Swift string literal. */
export function swiftString(value: string): string {
  let out = '"';
  for (const character of value) {
    const code = character.codePointAt(0)!;
    if (character === "\\") out += "\\\\";
    else if (character === '"') out += '\\"';
    else if (character === "\n") out += "\\n";
    else if (character === "\r") out += "\\r";
    else if (character === "\t") out += "\\t";
    else if (code < 0x20 || code === 0x7f) out += `\\u{${code.toString(16)}}`;
    else out += character;
  }
  return `${out}"`;
}

function escapeXml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/**
 * Build constants. `dev` is true only under `farm dev --mobile`: it enables the `-FarmServer` and
 * `-FarmPool` launch arguments and per-call bridge logs, which a `farm build --mobile` app must
 * never honor.
 */
export function createFarmBuild(context: MobileShellContext): string {
  const symbols = context.manifest.tabs.map((tab) => swiftString(resolveTabSymbol(tab.icon)));
  return `// ${GENERATED}

enum FarmBuild {
    /// True only under farm dev --mobile: launch overrides and per-call bridge logs.
    static let dev = ${context.command === "dev"}
    /// The first screen when there are no tabs: the app's base path.
    static let startPath = ${swiftString(context.basePath || "/")}
    /// The app's base path ("" or "/base"), in front of /__farm/mobile/session.
    static let basePath = ${swiftString(context.basePath)}
    /// auth.basePath, or "" without auth: the only routes native screens sign in to.
    static let authBasePath = ${swiftString(context.authBasePath ?? "")}
    /// SF Symbols for mobile.tabs, in order.
    static let tabIcons: [String] = [${symbols.join(", ")}]
}
`;
}

type PlistValue = string | boolean | PlistValue[] | { [key: string]: PlistValue };

function plistValue(value: PlistValue, indent: string): string {
  if (typeof value === "boolean") return `${indent}<${value}/>`;
  if (typeof value === "string") return `${indent}<string>${escapeXml(value)}</string>`;
  const inner = `${indent}\t`;
  if (Array.isArray(value)) {
    if (value.length === 0) return `${indent}<array/>`;
    return `${indent}<array>\n${value.map((item) => plistValue(item, inner)).join("\n")}\n${indent}</array>`;
  }
  const keys = Object.keys(value).sort();
  if (keys.length === 0) return `${indent}<dict/>`;
  const entries = keys.map(
    (key) => `${inner}<key>${escapeXml(key)}</key>\n${plistValue(value[key]!, inner)}`,
  );
  return `${indent}<dict>\n${entries.join("\n")}\n${indent}</dict>`;
}

function plist(root: { [key: string]: PlistValue }): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
${plistValue(root, "")}
</plist>
`;
}

/**
 * HTTPS only, except under `farm dev --mobile`: local networking (loopback, LAN addresses and
 * `.local` names) and the dev server's own host name.
 */
export function createTransportSecurity(
  context: MobileShellContext,
): { [key: string]: PlistValue } | undefined {
  if (context.command !== "dev") return undefined;
  const server = new URL(context.manifest.server);
  const hosts = new Set(["localhost"]);
  const host = server.hostname.replace(/^\[|\]$/g, "").toLowerCase();
  // App Transport Security takes domain names here; IP addresses are local networking.
  if (server.protocol === "http:" && isIP(host) === 0) hosts.add(host);
  return {
    NSAllowsLocalNetworking: true,
    NSExceptionDomains: Object.fromEntries(
      [...hosts].sort().map((name) => [name, { NSExceptionAllowsInsecureHTTPLoads: true }]),
    ),
  };
}

/**
 * The usage strings `mobile.modules` sets, such as `NSCameraUsageDescription`. Core rejects two
 * modules that set one key to different strings.
 */
export function createUsageDescriptions(context: MobileShellContext): Record<string, string> {
  // A core from before `mobile.modules` resolves no `modules` entry.
  return Object.assign(
    {},
    ...Object.values(context.mobile.modules ?? {}).map((module) => module.usage),
  );
}

export function createInfoPlist(context: MobileShellContext): string {
  const transport = createTransportSecurity(context);
  const orientations = [
    "UIInterfaceOrientationPortrait",
    "UIInterfaceOrientationLandscapeLeft",
    "UIInterfaceOrientationLandscapeRight",
  ];
  return plist({
    CFBundleDevelopmentRegion: "$(DEVELOPMENT_LANGUAGE)",
    CFBundleDisplayName: context.mobile.name,
    CFBundleExecutable: "$(EXECUTABLE_NAME)",
    CFBundleIdentifier: "$(PRODUCT_BUNDLE_IDENTIFIER)",
    CFBundleInfoDictionaryVersion: "6.0",
    CFBundleName: "$(PRODUCT_NAME)",
    CFBundlePackageType: "$(PRODUCT_BUNDLE_PACKAGE_TYPE)",
    CFBundleShortVersionString: "$(MARKETING_VERSION)",
    CFBundleVersion: "$(CURRENT_PROJECT_VERSION)",
    LSRequiresIPhoneOS: true,
    ...(transport
      ? {
          NSAppTransportSecurity: transport,
          // A device reaching the dev server on the LAN asks for local network access.
          NSLocalNetworkUsageDescription: "Connects to the Farm dev server on your network.",
        }
      : {}),
    UIApplicationSceneManifest: { UIApplicationSupportsMultipleScenes: false },
    UIApplicationSupportsIndirectInputEvents: true,
    UILaunchScreen: { UIColorName: "LaunchBackground" },
    UIRequiredDeviceCapabilities: ["arm64"],
    UISupportedInterfaceOrientations: orientations,
    "UISupportedInterfaceOrientations~ipad": [
      ...orientations,
      "UIInterfaceOrientationPortraitUpsideDown",
    ],
    // After the shell's own keys, so a module's NSLocalNetworkUsageDescription wins.
    ...createUsageDescriptions(context),
  });
}

/** A stable 24-digit object id, so the project file is the same on every run. */
function pbxId(key: string): string {
  return createHash("sha1")
    .update(`farm.js/mobile/ios:${key}`)
    .digest("hex")
    .slice(0, 24)
    .toUpperCase();
}

type PbxValue = string | number | PbxValue[] | { [key: string]: PbxValue };

function pbxString(value: string | number): string {
  const text = String(value);
  return /^[A-Za-z0-9_$/.]+$/.test(text)
    ? text
    : `"${text.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n")}"`;
}

function pbxValue(value: PbxValue, indent: string, names: Map<string, string>): string {
  if (typeof value === "string" || typeof value === "number") {
    const name = typeof value === "string" ? names.get(value) : undefined;
    return name ? `${value} /* ${name} */` : pbxString(value);
  }
  const inner = `${indent}\t`;
  if (Array.isArray(value)) {
    return `(\n${value.map((item) => `${inner}${pbxValue(item, inner, names)},\n`).join("")}${indent})`;
  }
  const keys = Object.keys(value).sort((left, right) =>
    left === "isa" ? -1 : right === "isa" ? 1 : left < right ? -1 : left > right ? 1 : 0,
  );
  return `{\n${keys.map((key) => `${inner}${pbxString(key)} = ${pbxValue(value[key]!, inner, names)};\n`).join("")}${indent}}`;
}

/** Page shells (`mobile.shells`), read by `PageShells.swift`; a folder reference in the bundle. */
export const IOS_PAGE_SHELLS_DIR = "farm-shells";

const FILE_TYPES: Record<string, { type: string; phase?: "sources" | "resources" }> = {
  [IOS_PAGE_SHELLS_DIR]: { type: "folder", phase: "resources" },
  ".swift": { type: "sourcecode.swift", phase: "sources" },
  ".xcassets": { type: "folder.assetcatalog", phase: "resources" },
  ".json": { type: "text.json", phase: "resources" },
  ".js": { type: "sourcecode.javascript", phase: "resources" },
  ".plist": { type: "text.plist.xml" },
};

/**
 * `App.xcodeproj/project.pbxproj` for the files under `App/`: one iOS app target, Swift sources,
 * and bundle resources (the asset catalog, farm-routes.json, farm-bridge.js). Object ids derive
 * from the file names, so the same files give the same project.
 */
export function createProjectFile(context: MobileShellContext, files: readonly string[]): string {
  const entries = [
    ...new Set(
      files
        .filter((file) => file.startsWith(`${IOS_TARGET}/`))
        .map((file) => file.slice(IOS_TARGET.length + 1).split("/")[0]!),
    ),
  ].sort();
  const objects: Record<string, { [key: string]: PbxValue }> = {};
  const names = new Map<string, string>();
  const add = (key: string, name: string, object: { [key: string]: PbxValue }) => {
    const id = pbxId(key);
    if (objects[id]) throw new Error(`Duplicate Xcode object ${key}`);
    objects[id] = object;
    names.set(id, name);
    return id;
  };

  const sources: string[] = [];
  const resources: string[] = [];
  const children: string[] = [];
  for (const entry of entries) {
    const kind = FILE_TYPES[entry] ?? FILE_TYPES[path.extname(entry)];
    if (!kind) throw new Error(`No Xcode file type for ${IOS_TARGET}/${entry}`);
    const ref = add(`file:${entry}`, entry, {
      isa: "PBXFileReference",
      lastKnownFileType: kind.type,
      path: entry,
      sourceTree: "<group>",
    });
    children.push(ref);
    if (!kind.phase) continue;
    const phase = kind.phase === "sources" ? "Sources" : "Resources";
    const build = add(`build:${entry}`, `${entry} in ${phase}`, {
      isa: "PBXBuildFile",
      fileRef: ref,
    });
    (kind.phase === "sources" ? sources : resources).push(build);
  }

  const product = add("product", `${IOS_TARGET}.app`, {
    isa: "PBXFileReference",
    explicitFileType: "wrapper.application",
    includeInIndex: 0,
    path: `${IOS_TARGET}.app`,
    sourceTree: "BUILT_PRODUCTS_DIR",
  });
  const appGroup = add("group:app", IOS_TARGET, {
    isa: "PBXGroup",
    children,
    path: IOS_TARGET,
    sourceTree: "<group>",
  });
  const productsGroup = add("group:products", "Products", {
    isa: "PBXGroup",
    children: [product],
    name: "Products",
    sourceTree: "<group>",
  });
  const mainGroup = add("group:main", "", {
    isa: "PBXGroup",
    children: [appGroup, productsGroup],
    sourceTree: "<group>",
  });
  names.delete(mainGroup);

  const phase = (isa: string, name: string, files: string[]) =>
    add(`phase:${name}`, name, {
      isa,
      buildActionMask: 2147483647,
      files,
      runOnlyForDeploymentPostprocessing: 0,
    });
  const sourcesPhase = phase("PBXSourcesBuildPhase", "Sources", sources);
  const frameworksPhase = phase("PBXFrameworksBuildPhase", "Frameworks", []);
  const resourcesPhase = phase("PBXResourcesBuildPhase", "Resources", resources);

  const shared: Record<string, PbxValue> = {
    ALWAYS_SEARCH_USER_PATHS: "NO",
    CLANG_ENABLE_MODULES: "YES",
    CLANG_ENABLE_OBJC_ARC: "YES",
    ENABLE_STRICT_OBJC_MSGSEND: "YES",
    GCC_C_LANGUAGE_STANDARD: "gnu17",
    IPHONEOS_DEPLOYMENT_TARGET: IOS_DEPLOYMENT_TARGET,
    SDKROOT: "iphoneos",
  };
  const projectDebug = add("config:project:Debug", "Debug", {
    isa: "XCBuildConfiguration",
    buildSettings: {
      ...shared,
      COPY_PHASE_STRIP: "NO",
      DEBUG_INFORMATION_FORMAT: "dwarf",
      ENABLE_TESTABILITY: "YES",
      GCC_OPTIMIZATION_LEVEL: 0,
      GCC_PREPROCESSOR_DEFINITIONS: ["DEBUG=1", "$(inherited)"],
      ONLY_ACTIVE_ARCH: "YES",
      SWIFT_ACTIVE_COMPILATION_CONDITIONS: "DEBUG",
      SWIFT_OPTIMIZATION_LEVEL: "-Onone",
    },
    name: "Debug",
  });
  const projectRelease = add("config:project:Release", "Release", {
    isa: "XCBuildConfiguration",
    buildSettings: {
      ...shared,
      COPY_PHASE_STRIP: "NO",
      DEBUG_INFORMATION_FORMAT: "dwarf-with-dsym",
      ENABLE_NS_ASSERTIONS: "NO",
      SWIFT_COMPILATION_MODE: "wholemodule",
      SWIFT_OPTIMIZATION_LEVEL: "-O",
      VALIDATE_PRODUCT: "YES",
    },
    name: "Release",
  });
  const target: Record<string, PbxValue> = {
    ASSETCATALOG_COMPILER_APPICON_NAME: "AppIcon",
    ASSETCATALOG_COMPILER_GLOBAL_ACCENT_COLOR_NAME: "AccentColor",
    CODE_SIGN_STYLE: "Automatic",
    CURRENT_PROJECT_VERSION: 1,
    GENERATE_INFOPLIST_FILE: "NO",
    INFOPLIST_FILE: `${IOS_TARGET}/Info.plist`,
    LD_RUNPATH_SEARCH_PATHS: ["$(inherited)", "@executable_path/Frameworks"],
    MARKETING_VERSION: "1.0",
    PRODUCT_BUNDLE_IDENTIFIER: context.mobile.id,
    PRODUCT_NAME: "$(TARGET_NAME)",
    SUPPORTED_PLATFORMS: "iphoneos iphonesimulator",
    SWIFT_VERSION: "5.0",
    TARGETED_DEVICE_FAMILY: "1,2",
  };
  const targetDebug = add("config:target:Debug", "Debug", {
    isa: "XCBuildConfiguration",
    buildSettings: target,
    name: "Debug",
  });
  const targetRelease = add("config:target:Release", "Release", {
    isa: "XCBuildConfiguration",
    buildSettings: target,
    name: "Release",
  });
  const configList = (key: string, name: string, configurations: string[]) =>
    add(`list:${key}`, name, {
      isa: "XCConfigurationList",
      buildConfigurations: configurations,
      defaultConfigurationIsVisible: 0,
      defaultConfigurationName: "Release",
    });
  const targetList = configList(
    "target",
    `Build configuration list for PBXNativeTarget "${IOS_TARGET}"`,
    [targetDebug, targetRelease],
  );
  const projectList = configList(
    "project",
    `Build configuration list for PBXProject "${IOS_TARGET}"`,
    [projectDebug, projectRelease],
  );
  const nativeTarget = add("target", IOS_TARGET, {
    isa: "PBXNativeTarget",
    buildConfigurationList: targetList,
    buildPhases: [sourcesPhase, frameworksPhase, resourcesPhase],
    buildRules: [],
    dependencies: [],
    name: IOS_TARGET,
    productName: IOS_TARGET,
    productReference: product,
    productType: "com.apple.product-type.application",
  });
  const project = add("project", "Project object", {
    isa: "PBXProject",
    attributes: {
      BuildIndependentTargetsInParallel: 1,
      LastSwiftUpdateCheck: 1500,
      LastUpgradeCheck: 1500,
      TargetAttributes: { [nativeTarget]: { CreatedOnToolsVersion: "15.0" } },
    },
    buildConfigurationList: projectList,
    compatibilityVersion: "Xcode 14.0",
    developmentRegion: "en",
    hasScannedForEncodings: 0,
    knownRegions: ["en", "Base"],
    mainGroup,
    productRefGroup: productsGroup,
    projectDirPath: "",
    projectRoot: "",
    targets: [nativeTarget],
  });

  const sections = new Map<string, string[]>();
  for (const [id, object] of Object.entries(objects)) {
    const isa = object.isa as string;
    sections.set(isa, [...(sections.get(isa) ?? []), id]);
  }
  let body = "";
  for (const isa of [...sections.keys()].sort()) {
    body += `\n/* Begin ${isa} section */\n`;
    for (const id of sections.get(isa)!.sort()) {
      body += `\t\t${pbxValue(id, "\t\t", names)} = ${pbxValue(objects[id]!, "\t\t", names)};\n`;
    }
    body += `/* End ${isa} section */\n`;
  }
  return `// !$*UTF8*$!
{
\tarchiveVersion = 1;
\tclasses = {
\t};
\tobjectVersion = ${PBX_OBJECT_VERSION};
\tobjects = {
${body}\t};
\trootObject = ${project} /* Project object */;
}
`;
}

