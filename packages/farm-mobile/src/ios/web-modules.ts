import { readFileSync } from "node:fs";
import path from "node:path";
import type {
  FarmMobileAppModuleSpec,
  FarmNativeMethod,
  FarmNativeType,
  MobileGeneratedFile,
  MobileShellContext,
} from "@farm.js/core/mobile";
import { swiftString } from "./templates.js";

/**
 * Web screens' calls to app native modules on iOS (RFC 0004, 7.5), the twin of
 * `../android/web-modules.ts`. For each module with `mobile.modules.<name>.web`, core reads the
 * Promise methods of its Codegen spec; this file turns them into one `FarmAsyncPlugin` that checks
 * a call's JSON arguments against those types, then runs the method on the module instance React
 * Native screens use, by the Objective-C selector Codegen gives it. Nothing is generated when no
 * module opts in.
 */

/** The generated dispatcher, next to the React Native engine it calls. */
export const IOS_WEB_MODULES_FILE = "App/FarmWebModules.swift";

const GENERATED =
  "Generated by @farm.js/mobile/ios on every farm dev|build --mobile from the Codegen specs of " +
  "the modules mobile.modules opts in for web screens. Do not edit.";

const SCENE_DELEGATE = "App/SceneDelegate.swift";
const PLUGINS_FROM = `        // Device plugins reachable as native.<name>; none ship yet, so calls reject as unavailable.
        let plugins: [String: FarmPlugin] = [:]`;
const PLUGINS_TO = `        // App native modules web screens call as native.<name> (mobile.modules.<name>.web).
        let plugins = farmWebModules()`;

/** The runtime description of a spec type, which `convert` checks JSON against. */
function swiftType(type: FarmNativeType): string {
  const nullable = type.nullable ? ", nullable: true" : "";
  switch (type.type) {
    case "string":
    case "boolean":
    case "map":
      return `FarmWebType(${swiftString(type.type)}${nullable})`;
    case "number":
      return `FarmWebType("number"${nullable}${type.integer ? ", integer: true" : ""})`;
    case "literal": {
      const values = type.values
        .map((value) =>
          typeof value === "string"
            ? `.string(${swiftString(value)})`
            : `.number(${Number(value)})`,
        )
        .join(", ");
      return `FarmWebType("literal"${nullable}, values: [${values}])`;
    }
    case "array":
      return type.element
        ? `FarmWebType("array"${nullable}, element: ${swiftType(type.element)})`
        : `FarmWebType("array"${nullable})`;
    case "object":
      return `FarmWebType("object"${nullable}, properties: [${type.properties
        .map(
          (property) =>
            `FarmWebParam(${swiftString(property.name)}, ${property.optional}, ${swiftType(property.type)})`,
        )
        .join(", ")}])`;
    case "void":
    case "unknown":
      throw new Error(`A ${type.type} type is not a parameter type.`);
  }
}

/**
 * The selector of Codegen's Objective-C protocol method: the method's name takes the first
 * parameter, each later one its own name, then the promise's `resolve:reject:` (so `model()` is
 * `model:reject:`, and `vibrate(ms)` is `vibrate:resolve:reject:`).
 */
export function codegenSelector(method: Pick<FarmNativeMethod, "name" | "params">): string {
  return [...method.params.map((param) => param.name), "resolve", "reject"].reduce(
    (selector, name, index) => (index === 0 ? `${selector}:` : `${selector}${name}:`),
    method.name,
  );
}

/**
 * Why a method cannot be called from web screens on iOS, or undefined. Codegen passes an object
 * parameter with declared properties to Objective-C as a C++ struct, which the shell cannot build
 * from JSON; maps and arrays (dictionaries and arrays there) are fine.
 */
function iosUnsupported(module: string, method: FarmNativeMethod): string | undefined {
  const param = method.params.find((candidate) => candidate.type.type === "object");
  if (!param) return undefined;
  return (
    `${module}.${method.name} takes an object type (${param.name}), which Codegen passes to ` +
    "Objective-C as a C++ struct, so web screens cannot call it on iOS. Declare the parameter " +
    "as Object to call it from web screens on both platforms."
  );
}

function createModule(name: string, methods: FarmNativeMethod[]): string {
  const entries = methods.map((method) => {
    const params = method.params
      .map(
        (param) =>
          `FarmWebParam(${swiftString(param.name)}, ${param.optional}, ${swiftType(param.type)})`,
      )
      .join(", ");
    const unsupported = iosUnsupported(name, method);
    return (
      `            ${swiftString(method.name)}: FarmWebMethod(${swiftString(codegenSelector(method))}, [${params}]` +
      `${unsupported ? `, unavailable: ${swiftString(unsupported)}` : ""}),`
    );
  });
  return `        // ${name}: the Promise methods of its spec, as web screens send them.
        FarmWebModule(${swiftString(name)}, [
${entries.length > 0 ? entries.join("\n") : "            :"}
        ]),`;
}

const RUNTIME = `/**
 * One app module for web screens. \`callAsync\` checks a call's arguments against the spec on the
 * main thread, before anything runs; the method then runs on the module instance React Native
 * screens use, on its method queue, as a call from a native screen would.
 */
@MainActor
private final class FarmWebModule: FarmAsyncPlugin {
    let name: String
    private let methods: [String: FarmWebMethod]

    init(_ name: String, _ methods: [String: FarmWebMethod]) {
        self.name = name
        self.methods = methods
    }

    func callAsync(
        method: String,
        args: Any?,
        webView: WKWebView,
        reply: @escaping @Sendable (FarmCallReply) -> Void
    ) throws {
        guard let list = args as? [Any] else {
            throw invalid("\\(name).\\(method) takes its arguments as an array, such as [200].")
        }
        guard let spec = methods[method] else {
            throw FarmCallError(
                code: "unknown_method",
                message: "\\(name) has no method \\"\\(method)\\" that returns a Promise, and web screens call only those."
            )
        }
        if let reason = spec.unavailable {
            throw FarmCallError(code: "native_unavailable", message: reason)
        }
        let arguments = try checkArgs(method, list, spec.params)
        // The shared React Native runtime; a call before the first native screen starts it.
        guard let engine = FarmNativeScreens.engine as? ReactNativeEngine else {
            throw FarmCallError(
                code: "native_unavailable",
                message: "React Native is not running in this app, so \\(name) is unavailable."
            )
        }
        engine.callModule(name, selector: spec.selector, arguments: arguments, reply: reply)
    }

    /// The arguments as Codegen's Objective-C method takes them, NSNull for a missing optional.
    private func checkArgs(_ method: String, _ args: [Any], _ params: [FarmWebParam]) throws -> [Any] {
        if args.count > params.count {
            throw invalid("\\(name).\\(method) takes \\(params.count) argument\\(params.count == 1 ? "" : "s"), got \\(args.count).")
        }
        return try params.enumerated().map { index, param in
            let at = "\\(name).\\(method) argument \\(index + 1) (\\(param.name))"
            guard index < args.count else {
                if !param.optional { throw invalid("\\(at) is required.") }
                return NSNull()
            }
            return try convert(args[index], param.type, at, optional: param.optional)
        }
    }
}

/// A Promise method of a spec: Codegen's selector and its parameters.
private struct FarmWebMethod {
    let selector: String
    let params: [FarmWebParam]
    /// Why web screens cannot call it on iOS, if they cannot.
    let unavailable: String?

    init(_ selector: String, _ params: [FarmWebParam], unavailable: String? = nil) {
        self.selector = selector
        self.params = params
        self.unavailable = unavailable
    }
}

private enum FarmWebLiteral: Equatable {
    case string(String)
    case number(Double)

    var shown: String {
        switch self {
        case .string(let value): FarmBridge.json(value) ?? value
        case .number(let value): value == value.rounded() && abs(value) < 1e15 ? String(Int64(value)) : String(value)
        }
    }
}

/// A value a spec declares: string, number, boolean, literal, object, map, or array.
private final class FarmWebType {
    let kind: String
    let nullable: Bool
    let integer: Bool
    let values: [FarmWebLiteral]
    let element: FarmWebType?
    let properties: [FarmWebParam]

    init(
        _ kind: String,
        nullable: Bool = false,
        integer: Bool = false,
        values: [FarmWebLiteral] = [],
        element: FarmWebType? = nil,
        properties: [FarmWebParam] = []
    ) {
        self.kind = kind
        self.nullable = nullable
        self.integer = integer
        self.values = values
        self.element = element
        self.properties = properties
    }
}

private struct FarmWebParam {
    let name: String
    let optional: Bool
    let type: FarmWebType

    init(_ name: String, _ optional: Bool, _ type: FarmWebType) {
        self.name = name
        self.optional = optional
        self.type = type
    }
}

private func invalid(_ message: String) -> FarmCallError {
    FarmCallError(code: "invalid_args", message: message)
}

/// JSON booleans arrive as NSNumber too; only CFBoolean is true or false.
private func isBoolean(_ value: Any) -> Bool {
    guard let number = value as? NSNumber else { return false }
    return CFGetTypeID(number) == CFBooleanGetTypeID()
}

private func shown(_ value: Any) -> String {
    FarmBridge.json(value) ?? String(describing: value)
}

private func expected(_ type: FarmWebType) -> String {
    let base: String
    switch type.kind {
    case "string": base = "a string"
    case "number": base = type.integer ? "a whole number" : "a number"
    case "boolean": base = "true or false"
    case "literal": base = "one of " + type.values.map(\\.shown).joined(separator: ", ")
    case "array": base = "an array"
    default: base = "an object"
    }
    return type.nullable ? base + " or null" : base
}

/// \`value\` from JSON as the Objective-C type Codegen's method takes, or an \`invalid_args\` naming \`at\`.
private func convert(_ value: Any?, _ type: FarmWebType, _ at: String, optional: Bool = false) throws -> Any {
    guard let value, !(value is NSNull) else {
        if type.nullable || optional { return NSNull() }
        throw invalid("\\(at) must be \\(expected(type)), got null.")
    }
    let mismatch = { invalid("\\(at) must be \\(expected(type)), got \\(shown(value)).") }
    switch type.kind {
    case "string":
        guard let string = value as? String else { throw mismatch() }
        return string
    case "boolean":
        guard isBoolean(value), let flag = value as? NSNumber else { throw mismatch() }
        return flag
    case "number":
        guard !isBoolean(value), let number = (value as? NSNumber)?.doubleValue, number.isFinite else {
            throw mismatch()
        }
        if type.integer, number != number.rounded() || number < Double(Int32.min) || number > Double(Int32.max) {
            throw mismatch()
        }
        return NSNumber(value: number)
    case "literal":
        let literal: FarmWebLiteral
        if let string = value as? String {
            literal = .string(string)
        } else if !isBoolean(value), let number = value as? NSNumber {
            literal = .number(number.doubleValue)
        } else {
            throw mismatch()
        }
        guard type.values.contains(literal) else { throw mismatch() }
        return value
    case "map":
        guard let map = value as? [String: Any] else { throw mismatch() }
        return map
    case "object":
        guard let json = value as? [String: Any] else { throw mismatch() }
        let declared = Set(type.properties.map(\\.name))
        if let key = json.keys.sorted().first(where: { !declared.contains($0) }) {
            throw invalid("\\(at) has the property \\"\\(key)\\", which the spec does not declare.")
        }
        var object: [String: Any] = [:]
        for property in type.properties {
            let place = "\\(at).\\(property.name)"
            guard let entry = json[property.name] else {
                if !property.optional { throw invalid("\\(place) is required.") }
                continue
            }
            object[property.name] = try convert(entry, property.type, place, optional: property.optional)
        }
        return object
    case "array":
        guard let json = value as? [Any] else { throw mismatch() }
        guard let element = type.element else { return json }
        return try json.enumerated().map { index, item in try convert(item, element, "\\(at)[\\(index)]") }
    default:
        throw mismatch()
    }
}`;

/** The dispatcher file for the opted-in modules. */
function createWebModulesFile(
  modules: Array<{ name: string; methods: FarmNativeMethod[] }>,
): string {
  return `// ${GENERATED}
import Foundation
import WebKit

/// The FarmPlugin of each app module with mobile.modules.<name>.web (RFC 0004, 7.5). The bridge
/// dispatches \`call\` messages from web screens only to these modules, and only to the Promise
/// methods of their Codegen specs.
@MainActor
func farmWebModules() -> [String: FarmPlugin] {
    let modules: [FarmWebModule] = [
${modules.map((module) => createModule(module.name, module.methods)).join("\n")}
    ]
    return Dictionary(uniqueKeysWithValues: modules.map { ($0.name, $0 as FarmPlugin) })
}

${RUNTIME}
`;
}

/**
 * The opted-in modules the iOS app has code for: an Objective-C++ class in `src/native/` that
 * adopts the spec's Codegen protocol (`NativeDeviceSpec` for `NativeDevice.ts`).
 */
function iosModules(context: MobileShellContext): FarmMobileAppModuleSpec[] {
  const app = context.appModules;
  const specs = (app?.specs ?? []).filter((spec) => spec.web);
  if (!app || specs.length === 0) return [];
  const sources = app.ios
    .filter((file) => /\.(?:mm|m|h)$/.test(file))
    .map((file) => readFileSync(file, "utf8"));
  return specs.filter((spec) => {
    const protocol = `${path.basename(spec.file).replace(/\.\w+$/, "")}Spec`;
    const adopts = new RegExp(`\\b${protocol}\\b`);
    return sources.some((source) => adopts.test(source));
  });
}

/**
 * The files that change when app modules opt in for web screens: the dispatcher and
 * `SceneDelegate` registering it. Empty when none opts in, and when the iOS app cannot run one:
 * without React Native (no native screen on iOS), or without the module's iOS code. Those modules
 * stay unregistered, so `native.<name>.available()` is false and calls reject as unavailable,
 * as in a browser.
 */
export function createIosWebModules(
  context: MobileShellContext,
  files: readonly MobileGeneratedFile[],
): MobileGeneratedFile[] {
  if (!context.native) return [];
  const specs = iosModules(context);
  if (specs.length === 0) return [];
  const scene = files.find((file) => file.path === SCENE_DELEGATE);
  const source = String(scene?.contents ?? "");
  if (!scene || !source.includes(PLUGINS_FROM)) {
    throw new Error(`${SCENE_DELEGATE} no longer contains "${PLUGINS_FROM.trim()}".`);
  }
  return [
    {
      path: IOS_WEB_MODULES_FILE,
      contents: createWebModulesFile(
        specs.map((spec) => ({ name: spec.name, methods: spec.web!.methods })),
      ),
    },
    { ...scene, contents: source.replace(PLUGINS_FROM, PLUGINS_TO) },
  ];
}
