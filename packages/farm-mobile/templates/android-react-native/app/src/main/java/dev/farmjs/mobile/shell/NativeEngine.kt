/**
 * React Native for `page.native.tsx` screens (RFC 0004, 7.2). Generated by @farm.js/mobile/android
 * only for apps with React Native screens. New architecture only: Hermes bytecode, Fabric and
 * bridgeless TurboModules. One runtime is shared by every native screen, each its own surface.
 */
internal fun createFarmNativeEngine(activity: AppCompatActivity, config: RouteConfig): FarmNativeEngine? =
    ReactNativeEngine(activity, config)

class ReactNativeEngine(
    private val activity: AppCompatActivity,
    private val config: RouteConfig,
) : FarmNativeEngine, DefaultLifecycleObserver {
    private val dev = activity.resources.getBoolean(R.bool.farm_dev)
    private var host: ReactHost? = null

    init {
        activity.lifecycle.addObserver(this)
    }

    /** The shared runtime, created on first use. Null once it failed in a build that is not dev. */
    private fun host(): ReactHost? {
        if (failure != null && !dev) return null
        failure = null
        host?.let { return it }
        return try {
            val started = SystemClock.uptimeMillis()
            val context = activity.applicationContext
            loadLibraries(context)
            val created = DefaultReactHost.getDefaultReactHost(
                context = context,
                packageList = listOf(MainReactPackage(), FarmShellPackage()),
                jsMainModulePath = activity.getString(R.string.farm_native_main_module),
                jsBundleAssetPath = BUNDLE_ASSET,
                useDevSupport = dev,
                exceptionHandler = { error -> fail(error) },
            )
            // No fallback when the instance is torn down: in development a Fast Refresh full reload
            // (any edit to a screen that exports more than a component) tears it down too, and
            // React Native restarts the open surfaces. A fatal error shows React Native's error screen
            // there; builds report it to exceptionHandler.
            created.onHostResume(activity) {}
            Log.i(Navigator.TAG, "react-native host ready in ${SystemClock.uptimeMillis() - started}ms dev=$dev")
            host = created
            created
        } catch (error: Throwable) {
            fail(error)
            null
        }
    }

    override fun warm() {
        val started = SystemClock.uptimeMillis()
        // React Native's libraries take a few hundred milliseconds to load; keep that off the
        // main thread, which is drawing the first screen.
        Thread {
            try {
                loadLibraries(activity.applicationContext)
            } catch (error: Throwable) {
                fail(error)
                return@Thread
            }
            main.post { startHost(started) }
        }.apply { name = "farm-react-native-load" }.start()
    }

    private fun startHost(started: Long) {
        if (activity.isDestroyed) return
        val reactHost = host() ?: return
        reactHost.addReactInstanceEventListener(object : ReactInstanceEventListener {
            override fun onReactContextInitialized(context: ReactContext) {
                reactHost.removeReactInstanceEventListener(this)
                Log.i(Navigator.TAG, "react-native warm in ${SystemClock.uptimeMillis() - started}ms")
            }
        })
        // Loads Hermes and evaluates the bundle off the main thread; failures reach fail().
        reactHost.start()
    }

    override fun open(host: FarmNativeHost, rule: RouteConfig.Rule, url: Uri): FarmNativeContent? {
        val module = rule.module ?: return null
        val reactHost = host() ?: return null
        val id = nextScreen++
        val props = Bundle().apply {
            putInt("screen", id)
            putString("url", url.toString())
            putString("route", rule.route ?: url.path ?: "/")
            putString("server", config.server.toString())
        }
        val surface = reactHost.createSurface(activity, module, props)
        screens[id] = host
        surface.start()
        val view = surface.view ?: return null.also { screens.remove(id) }
        return FarmNativeContent(view, title = "") {
            screens.remove(id)
            surface.stop()
            surface.detach()
        }
    }

    override fun onResume(owner: LifecycleOwner) {
        host?.onHostResume(activity) {}
    }

    override fun onPause(owner: LifecycleOwner) {
        host?.onHostPause(activity)
    }

    override fun onDestroy(owner: LifecycleOwner) {
        host?.onHostDestroy(activity)
        if (FarmNativeScreens.engine === this) FarmNativeScreens.engine = null
    }

    companion object {
        /** The Hermes bytecode `farm build --mobile` bundles into the app's assets. */
        const val BUNDLE_ASSET = "farm-native.hbc"

        private var nextScreen = 1
        private var loaded = false
        private val main = Handler(Looper.getMainLooper())

        /** Once per process: feature flags may not be overridden after React Native read them. */
        @Synchronized
        private fun loadLibraries(context: android.content.Context) {
            if (loaded) return
            SoLoader.init(context, OpenSourceMergedSoMapping)
            // Loads libreactnative, then libappmodules (src/main/jni) with the core module provider.
            DefaultNewArchitectureEntryPoint.load()
            loaded = true
        }

        /** Open native screens by id, so the FarmShell module can reach their navigator host. */
        internal val screens = java.util.concurrent.ConcurrentHashMap<Int, FarmNativeHost>()

        /** Why the runtime failed; every native screen shows its web twin after a failure. */
        @Volatile
        internal var failure: String? = null

        internal fun fail(error: Throwable) {
            val reason = "${error.javaClass.simpleName}: ${error.message}"
            Log.e(Navigator.TAG, "react-native failed, native screens fall back to web: $reason", error)
            failure = reason
            main.post { screens.values.toList().forEach { it.fallback(reason) } }
        }
    }
}

/** `NativeModules.FarmShell` in JS: what `@farm.js/native` calls to reach the navigator. */
class FarmShellModule(context: ReactApplicationContext) : ReactContextBaseJavaModule(context) {
    override fun getName() = NAME

    private fun screen(id: Double) = ReactNativeEngine.screens[id.toInt()]

    @ReactMethod
    fun visit(screen: Double, url: String, replace: Boolean) {
        screen(screen)?.visit(Uri.parse(url), replace)
    }

    @ReactMethod
    fun fallback(screen: Double, reason: String) {
        screen(screen)?.fallback(reason)
    }

    @ReactMethod
    fun setTitle(screen: Double, title: String) {
        screen(screen)?.setTitle(title)
    }

    @ReactMethod
    fun rendered(screen: Double) {
        screen(screen)?.rendered()
    }

    companion object {
        const val NAME = "FarmShell"
    }
}

class FarmShellPackage : BaseReactPackage() {
    override fun getModule(name: String, reactContext: ReactApplicationContext): NativeModule? =
        if (name == FarmShellModule.NAME) FarmShellModule(reactContext) else null

    override fun getReactModuleInfoProvider() = ReactModuleInfoProvider {
        mapOf(
            FarmShellModule.NAME to ReactModuleInfo(
                FarmShellModule.NAME,
                FarmShellModule::class.java.name,
                false,
                false,
                false,
                false,
            ),
        )
    }
}
