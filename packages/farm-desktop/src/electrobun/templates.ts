import path from "node:path";
import type { DesktopShellContext } from "@farm.js/core/desktop";

/** Where the Farm server output lands inside the app's `Resources/app` folder. */
export const SERVER_RESOURCE_DIR = "farm";

/**
 * The macOS icon set Electrobun turns into AppIcon.icns. One 1024px image is a valid set; the
 * OS scales it for smaller sizes.
 */
export const ICONSET_DIR = "icon.iconset";
export const ICONSET_IMAGE = `${ICONSET_DIR}/icon_512x512@2x.png`;

function toImportPath(from: string, to: string): string {
  const relative = path.relative(from, to).split(path.sep).join("/");
  return relative.startsWith(".") ? relative : `./${relative}`;
}

/** `electrobun.config.ts` for the generated shell project. */
export function createElectrobunConfig(context: DesktopShellContext): string {
  const { desktop } = context;
  const serverSource = toImportPath(context.shellDir, context.serverDir);
  const config = {
    app: {
      name: desktop.name,
      identifier: desktop.id,
      version: desktop.version,
    },
    build: {
      bun: { entrypoint: "main.ts" },
      // The Farm server built for Bun. main.ts imports its entry from Resources/app/farm.
      copy: { [serverSource]: SERVER_RESOURCE_DIR },
      // The system WebView (WKWebView, WebView2, WebKitGTK): no bundled Chromium.
      mac: { bundleCEF: false, createDmg: false, icons: ICONSET_DIR },
      linux: { bundleCEF: false },
      win: { bundleCEF: false },
    },
    runtime: { exitOnLastWindowClosed: true },
  };
  return `// Generated by @farm.js/desktop/electrobun on every farm dev|build --desktop. Do not edit.
export default ${JSON.stringify(config, null, 2)};
`;
}

/**
 * The Electrobun main process: start the Farm server in-process on 127.0.0.1:0, open the
 * window at the one-time handshake URL, keep it on the app's origin, and stop the server
 * through Farm's shutdown before the app quits. Under `farm dev --desktop` it opens the window
 * on the dev server instead.
 */
export function createElectrobunMain(context: DesktopShellContext): string {
  const { desktop } = context;
  const hooksImport = context.hooksFile
    ? `import farmDesktopHooks from ${JSON.stringify(toImportPath(context.shellDir, context.hooksFile))};`
    : "const farmDesktopHooks = {};";
  const options = {
    title: desktop.window.title,
    width: desktop.window.width,
    height: desktop.window.height,
    basePath: context.basePath,
    serverEntry: `${SERVER_RESOURCE_DIR}/server/index.mjs`,
  };
  return `// Generated by @farm.js/desktop/electrobun on every farm dev|build --desktop. Do not edit.
import Electrobun, { BrowserWindow, BuildConfig, PATHS, Utils } from "electrobun/main";
import { randomBytes } from "node:crypto";
import { mkdir } from "node:fs/promises";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
${hooksImport}

const options = ${JSON.stringify(options, null, 2)};
const HANDSHAKE_PATH = "/__farm/desktop/handshake";

function takeEnv(name) {
  const value = process.env[name];
  delete process.env[name];
  return value;
}

async function startFarm() {
  const build = await BuildConfig.get();
  const devUrl = process.env.FARM_DESKTOP_DEV_URL;
  const devToken = takeEnv("FARM_DESKTOP_HANDSHAKE_TOKEN");
  takeEnv("FARM_DESKTOP_SECRET");
  if (!build.isPackaged && devUrl && devToken) {
    return {
      mode: "development",
      origin: devUrl,
      port: Number(new URL(devUrl).port),
      handshakeToken: devToken,
      stop: async () => {},
    };
  }

  const dataDir = Utils.paths.userData;
  await mkdir(dataDir, { recursive: true });
  const secret = randomBytes(32).toString("base64url");
  const handshakeToken = randomBytes(32).toString("base64url");
  // A computed specifier, so Electrobun's bundler leaves the server to load at runtime.
  const entry = pathToFileURL(join(PATHS.RESOURCES_FOLDER, "app", options.serverEntry)).href;
  const { start } = await import(entry);
  const server = await start({ secret, handshakeToken, dataDir });
  return { mode: "production", ...server, handshakeToken };
}

const farm = await startFarm();
// sandbox: page scripts, and every frame in the page, get no Electrobun RPC bridge. Unsandboxed,
// they could load URLs or run JavaScript in any webview by its numeric id.
const win = new BrowserWindow({
  title: options.title,
  url: farm.origin + options.basePath + HANDSHAKE_PATH + "?t=" + encodeURIComponent(farm.handshakeToken),
  frame: { width: options.width, height: options.height },
  sandbox: true,
});

// The window stays on the app's origin (the last matching rule wins). Links elsewhere open
// in the system browser.
win.webview.setNavigationRules(["^*", farm.origin + "/*"]);
function openOutside(url) {
  if (typeof url !== "string") return;
  if (url === farm.origin || url.startsWith(farm.origin + "/")) return;
  if (/^(?:https?|mailto):/i.test(url)) Utils.openExternal(url);
}
Electrobun.events.on("will-navigate", (event) => openOutside(event.data?.detail));
Electrobun.events.on("new-window-open", (event) => {
  const detail = event.data?.detail;
  openOutside(typeof detail === "string" ? detail : detail?.url);
});

// Drain requests and run Farm's shutdown hooks, then quit for real.
let farmStopped = farm.mode === "development";
Electrobun.events.on("before-quit", (event) => {
  if (farmStopped) return;
  event.response = { allow: false };
  farm
    .stop()
    .catch((error) => console.error("[farm] desktop server shutdown failed:", error))
    .finally(() => {
      farmStopped = true;
      Utils.quit();
    });
});

await farmDesktopHooks.onReady?.({
  window: win,
  server: { origin: farm.origin, port: farm.port },
  mode: farm.mode,
});
`;
}
