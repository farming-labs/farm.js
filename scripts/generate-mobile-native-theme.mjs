#!/usr/bin/env node
// Writes packages/farm/src/mobile/native-theme.ts from Tailwind's default theme, the values the
// native tier resolves Tailwind classes to. Colors are converted from oklch to sRGB hex, since
// native views take sRGB. Run after a Tailwind upgrade: node scripts/generate-mobile-native-theme.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
// The Tailwind Farm builds with: core depends on it for built-in Tailwind support.
const require = createRequire(path.join(root, "packages", "farm", "package.json"));
const packageFile = require.resolve("tailwindcss/package.json");
const { version } = JSON.parse(readFileSync(packageFile, "utf8"));
const css = readFileSync(path.join(path.dirname(packageFile), "theme.css"), "utf8");

const vars = new Map();
for (const match of css.matchAll(/^\s*--([a-z0-9-]+):\s*([^;]+);/gm))
  vars.set(match[1], match[2].trim());

const rem = (value) => {
  const match = /^(-?[\d.]+)(rem|em)$/.exec(value);
  if (!match) throw new Error(`not a rem value: ${value}`);
  return Number(match[1]) * 16;
};
const ratio = (value) => {
  const calc = /^calc\(([\d.]+) \/ ([\d.]+)\)$/.exec(value);
  return calc ? Number(calc[1]) / Number(calc[2]) : Number(value);
};
const round = (value) => Math.round(value * 1000) / 1000;

function oklchToHex(value) {
  if (value.startsWith("#")) {
    const hex = value.slice(1);
    return `#${(hex.length === 3 ? [...hex].map((digit) => digit + digit).join("") : hex).toLowerCase()}`;
  }
  // `none` is the hue of a gray.
  const match = /^oklch\(([\d.]+)% ([\d.]+) ([\d.]+|none)\)$/.exec(value);
  if (!match) throw new Error(`unsupported color: ${value}`);
  const l = Number(match[1]) / 100;
  const c = Number(match[2]);
  const h = ((match[3] === "none" ? 0 : Number(match[3])) * Math.PI) / 180;
  const a = c * Math.cos(h);
  const b = c * Math.sin(h);
  const l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s_ = (l - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const linear = [
    4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
    -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
    -0.0041960863 * l_ - 0.7034186147 * m_ + 1.707614701 * s_,
  ];
  return `#${linear
    .map((channel) => {
      const clamped = Math.min(1, Math.max(0, channel));
      const gamma = clamped <= 0.0031308 ? 12.92 * clamped : 1.055 * clamped ** (1 / 2.4) - 0.055;
      return Math.round(gamma * 255)
        .toString(16)
        .padStart(2, "0");
    })
    .join("")}`;
}

const pick = (prefix, convert) =>
  Object.fromEntries(
    [...vars]
      .filter(([name]) => name.startsWith(prefix) && !name.includes("--", prefix.length))
      .map(([name, value]) => [name.slice(prefix.length), convert(value)]),
  );

const theme = {
  spacing: rem(vars.get("spacing")),
  colors: pick("color-", oklchToHex),
  text: Object.fromEntries(
    // Font sizes only, not `--text-shadow-*`.
    Object.entries(pick("text-", (value) => value))
      .filter(([, value]) => /^[\d.]+rem$/.test(value))
      .map(([size, fontSize]) => [size, rem(fontSize)])
      .map(([size, fontSize]) => [
        size,
        [fontSize, round(ratio(vars.get(`text-${size}--line-height`)) * fontSize)],
      ]),
  ),
  fontWeight: pick("font-weight-", Number),
  tracking: pick("tracking-", (value) => round(rem(value) / 16)),
  leading: pick("leading-", Number),
  radius: pick("radius-", rem),
  container: pick("container-", rem),
};

const json = (value) => JSON.stringify(value);
const source = `// Generated by scripts/generate-mobile-native-theme.mjs from tailwindcss ${version}. Do not edit.
// Lengths are in px (dp on Android, points on iOS); tracking is in em; text is [size, line height].

export const FARM_NATIVE_THEME = {
  spacing: ${theme.spacing},
  colors: ${json(theme.colors)},
  text: ${json(theme.text)},
  fontWeight: ${json(theme.fontWeight)},
  tracking: ${json(theme.tracking)},
  leading: ${json(theme.leading)},
  radius: ${json(theme.radius)},
  container: ${json(theme.container)},
} as const;
`;
const out = path.join(root, "packages", "farm", "src", "mobile", "native-theme.ts");
writeFileSync(out, source);
console.log(`wrote ${path.relative(root, out)} (${Object.keys(theme.colors).length} colors)`);
